-- Preflight for applying 20261015120000_lock_down_security_definer_functions.sql by hand.
--
-- Run against the target as the role the migrations runner uses there (supabase_admin for the
-- chart's migrations Job, postgres for the Supabase CLI):
--
--   psql "$TARGET_URL" -v ON_ERROR_STOP=1 -f tests/manual/security_definer_preflight.sql
--
-- Parts 1 and 2 are read-only. Part 2 writes security_definer_rollback.sql in the current
-- directory: statements that put back every public function's EXECUTE grants, the definitions
-- this migration replaces, and the view grants it revokes. Keep it until the change has run in
-- production for a while.
\set ON_ERROR_STOP on

-- 1. Can the migration apply here? -----------------------------------------------------------
select current_setting('server_version_num')::int >= 140000 as pg14_or_later_for_create_or_replace_trigger,
       current_user as connected_as,
       (select rolsuper from pg_roles where rolname = current_user) as is_superuser;

select
  exists (select 1 from supabase_migrations.schema_migrations where version = '20261014120000') as help_request_hardening_1085_applied,
  not exists (select 1 from supabase_migrations.schema_migrations where version = '20261015120000') as this_migration_not_yet_applied,
  (select max(version) from supabase_migrations.schema_migrations) as latest_applied;

-- CREATE OR REPLACE FUNCTION needs ownership (or superuser). Any row here would abort the apply.
select p.oid::regprocedure as cannot_replace, pg_get_userbyid(p.proowner) as owner
from pg_proc p
where p.pronamespace = 'public'::regnamespace
  and p.proname in ('authorize_for_admin', 'guard_admin_role_grant', 'update_gradebook_column_student_with_recalc',
                    'release_instructor_only_gradebook_column', 'soft_delete_survey', 'update_rubric_full',
                    'update_regrade_request_status', 'get_student_summary', 'trigger_signup_welcome_message',
                    'calculate_effective_due_date', 'calculate_final_due_date', 'user_is_in_help_request')
  and not pg_has_role(current_user, p.proowner, 'USAGE');

-- 2. Rollback script ---------------------------------------------------------------------------
-- Tuples-only, unaligned: the default aligned output would add headers, row-count footers and
-- '+' continuation markers to the file, which would not be valid SQL.
-- An empty search_path makes pg_get_functiondef schema-qualify every name (auth.uid(), not uid()),
-- so the file means the same thing whatever search_path it is later run under.
set search_path to '';
\pset tuples_only on
\pset format unaligned
\o security_definer_rollback.sql
\qecho '-- Generated by tests/manual/security_definer_preflight.sql before 20261015120000 was applied.'
\qecho 'begin;'
-- Function definitions this migration replaces.
select pg_get_functiondef(p.oid) || ';'
from pg_proc p
where p.pronamespace = 'public'::regnamespace
  and p.proname in ('authorize_for_admin', 'update_gradebook_column_student_with_recalc',
                    'release_instructor_only_gradebook_column', 'soft_delete_survey', 'update_rubric_full',
                    'update_regrade_request_status', 'get_student_summary', 'trigger_signup_welcome_message',
                    'calculate_effective_due_date', 'calculate_final_due_date', 'user_is_in_help_request');
-- EXECUTE grants on every function in public as they are now (NULL acl = the built-in default,
-- which is EXECUTE for PUBLIC).
select format('revoke all on function %s from public, anon, authenticated, service_role;', p.oid::regprocedure)
       || coalesce(
            (select string_agg(format(' grant execute on function %s to %s;', p.oid::regprocedure,
                                      case when a.grantee = 0 then 'public' else quote_ident(pg_get_userbyid(a.grantee)) end), '')
             from aclexplode(p.proacl) a
             where a.privilege_type = 'EXECUTE' and a.grantee <> p.proowner),
            case when p.proacl is null then format(' grant execute on function %s to public;', p.oid::regprocedure) else '' end)
from pg_proc p
where p.pronamespace = 'public'::regnamespace;
-- View grants this migration revokes from anon.
select format('grant %s on public.%I to anon;', string_agg(a.privilege_type, ', '), c.relname)
from pg_class c, aclexplode(c.relacl) a
where c.oid in ('public.assignments_with_effective_due_dates'::regclass,
                'public.submissions_with_grades_for_assignment_and_regression_test'::regclass)
  and a.grantee = 'anon'::regrole
group by c.relname;
-- Objects this migration adds (last, after the grants above, which name only functions that
-- existed when this ran).
\qecho 'drop trigger if exists guard_admin_role_grant on public.user_roles;'
\qecho 'drop trigger if exists guard_admin_role_grant on public.invitations;'
\qecho 'drop function if exists public.guard_admin_role_grant();'
\qecho 'drop function if exists public._due_date_lookup_allowed(bigint, uuid, bigint);'
\qecho 'drop function if exists public._calculate_effective_due_date(bigint, uuid);'
\qecho '-- Default privileges (section 1) are not restored here; re-grant per function instead.'
\qecho 'commit;'
\o
\pset format aligned
\pset tuples_only off
reset search_path;
\echo Wrote security_definer_rollback.sql

-- Make a column attempt p_attempt_number at a topic (NULL attempt number = the next one), or
-- clear it when p_topic_id is NULL.
CREATE OR REPLACE FUNCTION public.gradebook_columns_set_topic(p_column_id bigint, p_topic_id bigint, p_attempt_number integer)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_gradebook_id bigint;
  v_attempt integer := p_attempt_number;
BEGIN
  SELECT gradebook_id INTO v_gradebook_id FROM public.gradebook_columns WHERE id = p_column_id;
  IF v_gradebook_id IS NULL THEN
    RAISE EXCEPTION 'gradebook column % not found', p_column_id USING ERRCODE = 'P0002';
  END IF;
  PERFORM public.gradebook_require_instructor(v_gradebook_id);
  PERFORM pg_advisory_xact_lock(v_gradebook_id);

  IF p_topic_id IS NULL THEN
    UPDATE public.gradebook_columns SET topic_id = NULL, attempt_number = NULL WHERE id = p_column_id;
    RETURN;
  END IF;

  IF NOT EXISTS (SELECT 1 FROM public.gradebook_topics WHERE id = p_topic_id AND gradebook_id = v_gradebook_id) THEN
    RAISE EXCEPTION 'Topic % is not in this gradebook', p_topic_id USING ERRCODE = '22023';
  END IF;
  IF EXISTS (SELECT 1 FROM public.gradebook_topics WHERE standing_column_id = p_column_id) THEN
    RAISE EXCEPTION 'A topic''s standing column cannot also be an attempt' USING ERRCODE = '22023';
  END IF;
  IF v_attempt IS NULL THEN
    SELECT COALESCE(max(attempt_number), 0) + 1 INTO v_attempt
    FROM public.gradebook_columns WHERE topic_id = p_topic_id AND id <> p_column_id;
  END IF;

  UPDATE public.gradebook_columns SET topic_id = p_topic_id, attempt_number = v_attempt WHERE id = p_column_id;
END;
$$;

REVOKE ALL ON FUNCTION public.gradebook_columns_set_topic(bigint, bigint, integer) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.gradebook_columns_set_topic(bigint, bigint, integer) TO authenticated, service_role;

-- Set a topic's standing column and rule.
--   p_rule NULL                      -> the standing column keeps its own expression
--   p_rule set, p_standing_column_id -> that column's expression is generated from the attempts
--   p_rule set, no column            -> a new computed column is created for the standing
CREATE OR REPLACE FUNCTION public.gradebook_topic_set_standing(p_topic_id bigint, p_standing_column_id bigint, p_rule text)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_topic public.gradebook_topics;
  v_standing bigint := p_standing_column_id;
  v_slug text;
  v_max numeric;
  v_n integer := 1;
BEGIN
  SELECT * INTO v_topic FROM public.gradebook_topics WHERE id = p_topic_id;
  IF v_topic.id IS NULL THEN
    RAISE EXCEPTION 'topic % not found', p_topic_id USING ERRCODE = 'P0002';
  END IF;
  PERFORM public.gradebook_require_instructor(v_topic.gradebook_id);
  PERFORM pg_advisory_xact_lock(v_topic.gradebook_id);

  IF p_rule IS NOT NULL AND p_rule NOT IN ('best', 'latest') THEN
    RAISE EXCEPTION 'Unknown standing rule %', p_rule USING ERRCODE = '22023';
  END IF;

  IF v_standing IS NOT NULL THEN
    IF NOT EXISTS (SELECT 1 FROM public.gradebook_columns WHERE id = v_standing AND gradebook_id = v_topic.gradebook_id) THEN
      RAISE EXCEPTION 'Standing column % is not in this gradebook', v_standing USING ERRCODE = '22023';
    END IF;
    IF EXISTS (SELECT 1 FROM public.gradebook_columns WHERE id = v_standing AND topic_id IS NOT NULL) THEN
      RAISE EXCEPTION 'An attempt column cannot be a topic''s standing' USING ERRCODE = '22023';
    END IF;
  ELSIF p_rule IS NOT NULL THEN
    -- Create the standing column next to the topic's last attempt.
    SELECT max(max_score) INTO v_max FROM public.gradebook_columns WHERE topic_id = p_topic_id;
    v_slug := 'topic-' || p_topic_id || '-standing';
    WHILE EXISTS (SELECT 1 FROM public.gradebook_columns WHERE class_id = v_topic.class_id AND slug = v_slug) LOOP
      v_n := v_n + 1;
      v_slug := 'topic-' || p_topic_id || '-standing-' || v_n;
    END LOOP;
    -- Placed right after the topic's last attempt (the sort-order trigger shifts the rest), then
    -- compacted so it never lands inside a group.
    INSERT INTO public.gradebook_columns (class_id, gradebook_id, name, slug, max_score, score_expression, dependencies, sort_order)
    VALUES (v_topic.class_id, v_topic.gradebook_id, v_topic.name || ' (' || p_rule || ')', v_slug,
            COALESCE(v_max, 100), 'null', '{"gradebook_columns": []}'::jsonb,
            (SELECT max(sort_order) + 1 FROM public.gradebook_columns WHERE topic_id = p_topic_id))
    RETURNING id INTO v_standing;
    PERFORM public.gradebook_columns_compact_groups(v_topic.gradebook_id);
  END IF;

  UPDATE public.gradebook_topics
  SET standing_column_id = v_standing, standing_rule = p_rule
  WHERE id = p_topic_id;

  PERFORM public.gradebook_topic_regenerate_standing(p_topic_id);
  RETURN v_standing;
END;
$$;

REVOKE ALL ON FUNCTION public.gradebook_topic_set_standing(bigint, bigint, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.gradebook_topic_set_standing(bigint, bigint, text) TO authenticated, service_role;


-- Gradebook topics: "this column is attempt N at topic T", and which column is the topic's standing.
--
-- A group is a display partition of columns (one axis). Courses graded by topic have a second
-- axis that a group cannot also express: CS 2100 assesses each topic in several quizzes, and one
-- quiz session covers several topics. The session stays a group; the topic is stored here.
--
-- Gated by the `gradebook-topics` course feature, written disabled for existing classes by
-- 20261028120000_gradebook_column_groups.sql. Design record:
-- docs/adr/gradebook-column-groups-and-topics.md.
-- Down path: 20261028130000_gradebook_topics.down.sql.txt (not applied by the CLI).

-- ---------------------------------------------------------------------------------------------
-- 1. Schema
-- ---------------------------------------------------------------------------------------------

-- Target for the topic's standing-column foreign key.
ALTER TABLE public.gradebook_columns
  ADD CONSTRAINT gradebook_columns_id_gradebook_id_key UNIQUE (id, gradebook_id);

CREATE TABLE public.gradebook_topics (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  class_id bigint NOT NULL,
  gradebook_id bigint NOT NULL,
  name text NOT NULL,
  -- The column that holds the topic's result: an ordinary computed column, so it goes through the
  -- one recalculation pipeline like every other column.
  standing_column_id bigint,
  -- NULL: the standing column's expression is the instructor's own. 'best' / 'latest': the
  -- expression is generated from the topic's attempts and kept in sync with them.
  standing_rule text,
  CONSTRAINT gradebook_topics_name_not_blank CHECK (btrim(name) <> ''),
  CONSTRAINT gradebook_topics_standing_rule_check CHECK (standing_rule IN ('best', 'latest')),
  CONSTRAINT gradebook_topics_id_gradebook_id_key UNIQUE (id, gradebook_id),
  CONSTRAINT gradebook_topics_gradebook_class_fkey
    FOREIGN KEY (gradebook_id, class_id) REFERENCES public.gradebooks (id, class_id) ON DELETE CASCADE,
  CONSTRAINT gradebook_topics_standing_column_fkey
    FOREIGN KEY (standing_column_id, gradebook_id) REFERENCES public.gradebook_columns (id, gradebook_id)
    ON DELETE SET NULL (standing_column_id)
);

COMMENT ON TABLE public.gradebook_topics IS
  'A topic assessed by several attempt columns (gradebook_columns.topic_id + attempt_number), with an optional standing column that holds the result.';

CREATE UNIQUE INDEX gradebook_topics_gradebook_lower_name_key ON public.gradebook_topics (gradebook_id, lower(name));
CREATE INDEX gradebook_topics_class_id_idx ON public.gradebook_topics (class_id);
CREATE UNIQUE INDEX gradebook_topics_standing_column_key ON public.gradebook_topics (standing_column_id)
  WHERE standing_column_id IS NOT NULL;

ALTER TABLE public.gradebook_columns ADD COLUMN topic_id bigint;

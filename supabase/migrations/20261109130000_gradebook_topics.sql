-- The score expression for a topic's standing under its rule, listing every attempt by slug in
-- attempt order (so no attempt can be missed the way a slug glob misses `3cce` for `cce*`).
--   best   = the highest score among attempts that are not excused; missing attempts are skipped
--   latest = the score of the highest-numbered attempt that has a score and is not excused
-- A topic with no eligible attempt has no score. With no attempts at all the expression is "null".
CREATE OR REPLACE FUNCTION public.gradebook_topic_standing_expression(p_topic_id bigint)
RETURNS text
LANGUAGE plpgsql
STABLE
SET search_path = public, pg_temp
AS $$
DECLARE
  v_rule text;
  v_refs text[];
  v_expr text;
BEGIN
  SELECT standing_rule INTO v_rule FROM public.gradebook_topics WHERE id = p_topic_id;
  IF v_rule IS NULL THEN
    RETURN NULL;
  END IF;

  SELECT array_agg(format('gradebook_columns(%s)', to_json(slug)::text) ORDER BY attempt_number)
  INTO v_refs
  FROM public.gradebook_columns
  WHERE topic_id = p_topic_id;

  IF v_refs IS NULL THEN
    RETURN 'null';
  END IF;

  IF v_rule = 'best' THEN
    RETURN format('max(map([%s], f(x) = x.is_excused ? null : x.score))', array_to_string(v_refs, ', '));
  END IF;

  -- latest: a ternary chain from the last attempt back to the first
  v_expr := 'null';
  FOR i IN 1 .. array_length(v_refs, 1) LOOP
    v_expr := format('(%1$s.score != null and not %1$s.is_excused) ? %1$s.score : (%2$s)', v_refs[i], v_expr);
  END LOOP;
  RETURN v_expr;
END;
$$;

REVOKE ALL ON FUNCTION public.gradebook_topic_standing_expression(bigint) FROM PUBLIC, anon, authenticated;

-- Write the generated expression (and its dependencies) to the topic's standing column, if the
-- topic has a rule and the expression changed. Changing score_expression queues recalculation.
CREATE OR REPLACE FUNCTION public.gradebook_topic_regenerate_standing(p_topic_id bigint)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_standing bigint;
  v_expr text;
  v_deps jsonb;
BEGIN
  SELECT standing_column_id INTO v_standing
  FROM public.gradebook_topics WHERE id = p_topic_id AND standing_rule IS NOT NULL;
  IF v_standing IS NULL THEN
    RETURN;
  END IF;
  v_expr := public.gradebook_topic_standing_expression(p_topic_id);
  SELECT jsonb_build_object('gradebook_columns', COALESCE(jsonb_agg(id ORDER BY attempt_number), '[]'::jsonb))
  INTO v_deps
  FROM public.gradebook_columns WHERE topic_id = p_topic_id;

  UPDATE public.gradebook_columns
  SET score_expression = v_expr, dependencies = v_deps
  WHERE id = v_standing
    AND (score_expression IS DISTINCT FROM v_expr OR dependencies IS DISTINCT FROM v_deps);
END;
$$;

REVOKE ALL ON FUNCTION public.gradebook_topic_regenerate_standing(bigint) FROM PUBLIC, anon, authenticated;

-- Keep generated standings in sync when attempts join, leave, are renumbered or deleted.
CREATE OR REPLACE FUNCTION public.gradebook_columns_regenerate_topic_standing()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  IF TG_OP <> 'INSERT' AND OLD.topic_id IS NOT NULL THEN
    PERFORM public.gradebook_topic_regenerate_standing(OLD.topic_id);
  END IF;
  IF TG_OP <> 'DELETE' AND NEW.topic_id IS NOT NULL
     AND (TG_OP = 'INSERT' OR NEW.topic_id IS DISTINCT FROM OLD.topic_id OR NEW.attempt_number IS DISTINCT FROM OLD.attempt_number) THEN
    PERFORM public.gradebook_topic_regenerate_standing(NEW.topic_id);
  END IF;
  RETURN NULL;
END;
$$;

REVOKE ALL ON FUNCTION public.gradebook_columns_regenerate_topic_standing() FROM PUBLIC, anon, authenticated;

CREATE TRIGGER gradebook_columns_regenerate_topic_standing
  AFTER INSERT OR UPDATE OF topic_id, attempt_number OR DELETE ON public.gradebook_columns
  FOR EACH ROW EXECUTE FUNCTION public.gradebook_columns_regenerate_topic_standing();


-- Propose topics for a gradebook from what it already records, without writing anything.
--
-- 1. Standing by dependencies: a computed column whose dependencies are only manual columns (two
--    or more, or one if the names say topic/attempt), none used by any other computed column, is
--    a topic's standing; those columns are its attempts.
-- 2. Attempt number from a name starting "Attempt N", else from display order.
-- 3. Orphans: a manual column named "Attempt N: X" that no standing reads joins the proposed
--    topic whose attempts are named "Attempt M: X" (the glob-missed `3cce` case).
-- Conflicts are reported, never resolved: two columns proposed as the same attempt of a topic.
--
-- Returns { "topics": [ { name, standing_column_id, attempts: [ { column_id, attempt_number, source } ] } ],
--           "conflicts": [ { topic, attempt_number, column_ids } ] }
CREATE OR REPLACE FUNCTION public.gradebook_topics_suggest(p_gradebook_id bigint)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_topics jsonb := '[]'::jsonb;
  v_conflicts jsonb := '[]'::jsonb;
  s record;
  a record;
  v_attempts jsonb;
  v_claimed bigint[] := '{}';
  v_name text;
  v_label text;
  v_rank integer;
  v_num integer;
  v_topic jsonb;
  v_i integer;
BEGIN
  PERFORM public.gradebook_require_instructor(p_gradebook_id);

  FOR s IN
    WITH cols AS (
      SELECT id, name, slug, sort_order, score_expression, topic_id,
             ARRAY(SELECT jsonb_array_elements_text(COALESCE(dependencies->'gradebook_columns', '[]'::jsonb))::bigint) AS deps,
             (dependencies ? 'assignments' AND jsonb_array_length(dependencies->'assignments') > 0) AS reads_assignments
      FROM public.gradebook_columns
      WHERE gradebook_id = p_gradebook_id
    )
    SELECT c.id, c.name, c.deps
    FROM cols c
    WHERE c.score_expression IS NOT NULL
      AND NOT c.reads_assignments
      -- Two or more inputs; or one, when the column is named as a topic or its input as an attempt
      -- (a topic assessed once so far; a lone input is otherwise just a scaled copy).
      AND (array_length(c.deps, 1) >= 2
           OR (array_length(c.deps, 1) = 1 AND (
                 c.name ~* 'topic'
                 OR EXISTS (SELECT 1 FROM cols i WHERE i.id = c.deps[1] AND i.name ~* '^\s*attempt\s+\d'))))
      AND NOT EXISTS (SELECT 1 FROM public.gradebook_topics t WHERE t.standing_column_id = c.id)
      -- every input is a manual column of this gradebook that is not already an attempt
      AND NOT EXISTS (
        SELECT 1 FROM unnest(c.deps) d
        LEFT JOIN cols i ON i.id = d
        WHERE i.id IS NULL OR i.score_expression IS NOT NULL OR i.topic_id IS NOT NULL
      )
      -- and no other computed column reads any of them
      AND NOT EXISTS (
        SELECT 1 FROM cols o
        WHERE o.id <> c.id AND o.score_expression IS NOT NULL AND o.deps && c.deps
      )
    ORDER BY c.sort_order NULLS LAST, c.id
  LOOP
    v_attempts := '[]'::jsonb;
    v_rank := 0;
    FOR a IN
      SELECT id, name, substring(name FROM '^\s*[Aa]ttempt\s+(\d+)')::integer AS named_attempt
      FROM public.gradebook_columns WHERE id = ANY (s.deps)
      ORDER BY sort_order NULLS LAST, id
    LOOP
      v_rank := v_rank + 1;
      v_attempts := v_attempts || jsonb_build_array(jsonb_build_object(
        'column_id', a.id,
        'attempt_number', COALESCE(a.named_attempt, v_rank),
        'source', CASE WHEN a.named_attempt IS NOT NULL THEN 'name' ELSE 'order' END
      ));
    END LOOP;
    v_claimed := v_claimed || s.deps;

    -- Topic name: the standing's name without its decoration ("X Topic Max Score",
    -- "Quiz Topic: X", "X (max)"); if it has none, the attempts' "Attempt N: <label>" label.
    v_name := btrim(regexp_replace(regexp_replace(s.name,
      '^\s*qui[zt]\s+topic\s*:\s*', '', 'i'),
      '\s*(\(\s*(max|best|latest)\s*\)|topic\s+max\s+score|topic\s+score|max\s+score|standing)\s*$', '', 'i'));
    IF v_name = btrim(s.name) THEN
      SELECT min(lbl) INTO v_label FROM (
        SELECT btrim(substring(name FROM '^\s*[Aa]ttempt\s+\d+\s*[:\-–]\s*(.+)$')) AS lbl
        FROM public.gradebook_columns WHERE id = ANY (s.deps)
      ) x WHERE lbl IS NOT NULL;
      v_name := COALESCE(v_label, v_name);
    END IF;

    v_topics := v_topics || jsonb_build_array(jsonb_build_object(
      'name', v_name,
      'standing_column_id', s.id,
      'attempts', v_attempts
    ));
  END LOOP;

  -- Orphan attempts: "Attempt N: X" columns no proposed topic claimed, matched by label prefix.
  FOR a IN
    SELECT gc.id, substring(gc.name FROM '^\s*[Aa]ttempt\s+(\d+)')::integer AS num,
           lower(btrim(substring(gc.name FROM '^\s*[Aa]ttempt\s+\d+\s*[:\-–]\s*(.+)$'))) AS lbl
    FROM public.gradebook_columns gc
    WHERE gc.gradebook_id = p_gradebook_id
      AND gc.score_expression IS NULL
      AND gc.topic_id IS NULL
      AND gc.id <> ALL (v_claimed)
      AND gc.name ~* '^\s*attempt\s+\d+\s*[:\-–]'
    ORDER BY gc.sort_order NULLS LAST, gc.id
  LOOP
    FOR v_i IN 0 .. jsonb_array_length(v_topics) - 1 LOOP
      v_topic := v_topics->v_i;
      -- One label is a prefix of the other ("Coupling" / "Coupling, Cohesion, and Encapsulation"),
      -- or they share at least 12 leading characters ("Decorator, Strategy, Observer, Data Pull").
      IF a.lbl IS NOT NULL AND (
           lower(v_topic->>'name') LIKE a.lbl || '%' OR a.lbl LIKE lower(v_topic->>'name') || '%'
           OR public.gradebook_common_prefix_length(lower(v_topic->>'name'), a.lbl) >= 12
         ) THEN
        v_topics := jsonb_set(v_topics, ARRAY[v_i::text, 'attempts'],
          (v_topic->'attempts') || jsonb_build_array(jsonb_build_object(
            'column_id', a.id, 'attempt_number', a.num, 'source', 'orphan-name')));
        v_claimed := v_claimed || a.id;
        EXIT;
      END IF;
    END LOOP;
  END LOOP;

  -- Conflicts: two columns proposed as the same attempt of one topic.
  SELECT COALESCE(jsonb_agg(jsonb_build_object('topic', t.name, 'attempt_number', t.n, 'column_ids', t.ids)), '[]'::jsonb)
  INTO v_conflicts
  FROM (
    SELECT topic->>'name' AS name, (att->>'attempt_number')::integer AS n, jsonb_agg(att->'column_id') AS ids
    FROM jsonb_array_elements(v_topics) topic, jsonb_array_elements(topic->'attempts') att
    GROUP BY 1, 2
    HAVING count(*) > 1
  ) t;

  RETURN jsonb_build_object('topics', v_topics, 'conflicts', v_conflicts);
END;
$$;

REVOKE ALL ON FUNCTION public.gradebook_topics_suggest(bigint) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.gradebook_topics_suggest(bigint) TO authenticated, service_role;

-- Apply a (possibly edited) suggestion: create each topic, point its standing at the existing
-- column with no rule (so nothing is recalculated), and set its attempts. Fails as a whole on any
-- conflict, e.g. a duplicate attempt number.
CREATE OR REPLACE FUNCTION public.gradebook_topics_apply_suggestion(p_gradebook_id bigint, p_suggestion jsonb)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_class_id bigint;
  v_topic jsonb;
  v_att jsonb;
  v_topic_id bigint;
  v_created integer := 0;
BEGIN
  v_class_id := public.gradebook_require_instructor(p_gradebook_id);
  PERFORM pg_advisory_xact_lock(p_gradebook_id);

  FOR v_topic IN SELECT value FROM jsonb_array_elements(COALESCE(p_suggestion->'topics', '[]'::jsonb)) LOOP
    IF (v_topic->>'standing_column_id') IS NOT NULL AND NOT EXISTS (
      SELECT 1 FROM public.gradebook_columns WHERE id = (v_topic->>'standing_column_id')::bigint AND gradebook_id = p_gradebook_id
    ) THEN
      RAISE EXCEPTION 'Standing column % is not in this gradebook', v_topic->>'standing_column_id' USING ERRCODE = '22023';
    END IF;
    INSERT INTO public.gradebook_topics (class_id, gradebook_id, name, standing_column_id)
    VALUES (v_class_id, p_gradebook_id, btrim(v_topic->>'name'), (v_topic->>'standing_column_id')::bigint)
    RETURNING id INTO v_topic_id;
    v_created := v_created + 1;

    FOR v_att IN SELECT value FROM jsonb_array_elements(COALESCE(v_topic->'attempts', '[]'::jsonb)) LOOP
      UPDATE public.gradebook_columns
      SET topic_id = v_topic_id, attempt_number = (v_att->>'attempt_number')::integer
      WHERE id = (v_att->>'column_id')::bigint AND gradebook_id = p_gradebook_id;
      IF NOT FOUND THEN
        RAISE EXCEPTION 'Column % is not in this gradebook', v_att->>'column_id' USING ERRCODE = '22023';
      END IF;
    END LOOP;
  END LOOP;
  RETURN v_created;
END;
$$;

REVOKE ALL ON FUNCTION public.gradebook_topics_apply_suggestion(bigint, jsonb) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.gradebook_topics_apply_suggestion(bigint, jsonb) TO authenticated, service_role;


CREATE OR REPLACE FUNCTION public.gradebook_common_prefix_length(p_a text, p_b text)
RETURNS integer
LANGUAGE plpgsql
IMMUTABLE
SET search_path = public, pg_temp
AS $$
DECLARE
  i integer := 0;
BEGIN
  WHILE i < least(length(p_a), length(p_b)) AND substr(p_a, i + 1, 1) = substr(p_b, i + 1, 1) LOOP
    i := i + 1;
  END LOOP;
  RETURN i;
END;
$$;


RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  IF OLD.group_id IS NOT NULL
     AND (TG_OP = 'DELETE' OR NEW.group_id IS DISTINCT FROM OLD.group_id)
     AND NOT EXISTS (SELECT 1 FROM public.gradebook_columns WHERE group_id = OLD.group_id) THEN
    DELETE FROM public.gradebook_column_groups WHERE id = OLD.group_id;
  END IF;
  RETURN NULL;
END;
$$;


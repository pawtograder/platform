-- Plan the auto-group of a gradebook's ungrouped columns, without writing anything.
--
-- Returns {
--   "groups":  [{ "name", "column_ids": [..] }],          -- groups to create, in display order
--   "null_sort_order_column_ids": [..],                   -- columns to renumber after the max
--   "changes": [{ "column_id", "slug", "reason", "before", "after", "before_size", "after_size" }]
-- }
-- where a change is any column whose header or set of header-mates differs from what the legacy
-- heuristic renders today. Reasons:
--   null-sort-order  the column had no sort_order (the legacy order treated it as 0)
--   membership       its run differs: a sort_order gap no longer splits a family, or a
--                    neighbouring column with no sort_order no longer splits it
--   name             same members, different header text
CREATE OR REPLACE FUNCTION public.gradebook_columns_auto_group_plan(p_gradebook_id bigint)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SET search_path = public, pg_temp
AS $$
DECLARE
  r record;
  v_fam text;
  v_cur_fam text := NULL;
  v_cur_ids bigint[] := '{}';
  v_runs jsonb := '[]'::jsonb;          -- [{family, ids}]
  v_run jsonb;
  v_ids bigint[];
  v_names text[];
  v_prefix text;
  v_token text;
  v_base text;
  v_name text;
  v_candidate text;
  v_n integer;
  v_taken text[];
  v_groups jsonb := '[]'::jsonb;
  v_new_set jsonb := '{}'::jsonb;       -- column_id -> {ids, name}
  v_legacy jsonb := '{}'::jsonb;        -- column_id -> {ids, name}
  v_legacy_runs jsonb := '[]'::jsonb;
  v_last integer := -1;
  v_so integer;
  v_changes jsonb := '[]'::jsonb;
  v_nulls bigint[];
  v_before jsonb;
  v_after jsonb;
  v_reason text;
BEGIN
  -- Proposed runs: display order with NULL sort_order last; a family change or an already
  -- grouped column ends a run; gaps in sort_order do not.
  FOR r IN
    SELECT id, slug, group_id
    FROM public.gradebook_columns
    WHERE gradebook_id = p_gradebook_id
    ORDER BY sort_order NULLS LAST, id
  LOOP
    v_fam := CASE WHEN r.group_id IS NULL THEN public.gradebook_column_slug_family(r.slug) END;
    IF v_fam IS NULL OR v_fam IS DISTINCT FROM v_cur_fam THEN
      IF COALESCE(array_length(v_cur_ids, 1), 0) > 0 THEN
        v_runs := v_runs || jsonb_build_array(jsonb_build_object('family', v_cur_fam, 'ids', to_jsonb(v_cur_ids)));
      END IF;
      v_cur_ids := '{}';
      v_cur_fam := v_fam;
    END IF;
    IF v_fam IS NOT NULL THEN
      v_cur_ids := v_cur_ids || r.id;
    END IF;
  END LOOP;
  IF COALESCE(array_length(v_cur_ids, 1), 0) > 0 THEN
    v_runs := v_runs || jsonb_build_array(jsonb_build_object('family', v_cur_fam, 'ids', to_jsonb(v_cur_ids)));
  END IF;

  SELECT COALESCE(array_agg(lower(name)), '{}') INTO v_taken
  FROM public.gradebook_column_groups WHERE gradebook_id = p_gradebook_id;

  FOR v_run IN SELECT value FROM jsonb_array_elements(v_runs) LOOP
    SELECT array_agg(value::bigint) INTO v_ids FROM jsonb_array_elements_text(v_run->'ids');
    IF array_length(v_ids, 1) < 2 THEN
      CONTINUE;  -- a run of one stays ungrouped, as it renders today
    END IF;

    SELECT array_agg(gc.name ORDER BY gc.sort_order NULLS LAST, gc.id) INTO v_names
    FROM public.gradebook_columns gc WHERE gc.id = ANY (v_ids);

    -- Today's header, unless it misspells what the instructor calls these columns: when the
    -- members' common name prefix starts with the family token but its first word is not
    -- today's header ("Ai" for "AI Usage Log 1", "AI Usage Log 2"), use the prefix instead.
    -- "Lab 1", "Lab 2" keep "Labs"; "Participation Lec 1", ... keep "Participation".
    v_token := regexp_replace(lower(CASE
      WHEN (v_run->>'family') LIKE 'assignment-%' THEN split_part(v_run->>'family', '-', 2)
      ELSE v_run->>'family' END), '[^a-z0-9]', '', 'g');
    v_prefix := public.gradebook_common_name_prefix(v_names);
    v_base := public.gradebook_column_family_display_name(v_run->>'family');
    IF v_prefix IS NOT NULL AND v_token <> ''
       AND regexp_replace(lower(v_prefix), '[^a-z0-9]', '', 'g') LIKE v_token || '%'
       AND split_part(v_prefix, ' ', 1) IS DISTINCT FROM v_base THEN
      v_base := v_prefix;
    END IF;
    v_name := public.gradebook_pluralize(v_base);

    v_candidate := v_name;
    v_n := 1;
    WHILE lower(v_candidate) = ANY (v_taken) LOOP
      v_n := v_n + 1;
      v_candidate := v_name || ' (' || v_n || ')';
    END LOOP;
    v_taken := v_taken || lower(v_candidate);

    v_groups := v_groups || jsonb_build_array(jsonb_build_object('name', v_candidate, 'column_ids', to_jsonb(v_ids)));
    FOR i IN 1 .. array_length(v_ids, 1) LOOP
      v_new_set := v_new_set || jsonb_build_object(v_ids[i]::text, jsonb_build_object('ids', to_jsonb(v_ids), 'name', v_candidate));
    END LOOP;
  END LOOP;

  -- What the legacy heuristic renders: order by COALESCE(sort_order, 0), a run breaks on a family
  -- change or when sort_order is not exactly the previous + 1; header = pluralize(display name)
  -- for runs of two or more.
  v_cur_fam := NULL;
  v_cur_ids := '{}';
  FOR r IN
    SELECT id, slug, COALESCE(sort_order, 0) AS so
    FROM public.gradebook_columns
    WHERE gradebook_id = p_gradebook_id
    ORDER BY COALESCE(sort_order, 0), id
  LOOP
    v_fam := public.gradebook_column_slug_family(r.slug);
    IF NOT (v_last = -1 OR r.so = v_last + 1) OR v_fam IS DISTINCT FROM v_cur_fam THEN
      IF COALESCE(array_length(v_cur_ids, 1), 0) > 0 THEN
        v_legacy_runs := v_legacy_runs || jsonb_build_array(jsonb_build_object('family', v_cur_fam, 'ids', to_jsonb(v_cur_ids)));
      END IF;
      v_cur_ids := '{}';
      v_cur_fam := v_fam;
    END IF;
    v_cur_ids := v_cur_ids || r.id;
    v_last := r.so;
  END LOOP;
  IF COALESCE(array_length(v_cur_ids, 1), 0) > 0 THEN
    v_legacy_runs := v_legacy_runs || jsonb_build_array(jsonb_build_object('family', v_cur_fam, 'ids', to_jsonb(v_cur_ids)));
  END IF;
  FOR v_run IN SELECT value FROM jsonb_array_elements(v_legacy_runs) LOOP
    SELECT array_agg(value::bigint) INTO v_ids FROM jsonb_array_elements_text(v_run->'ids');
    IF array_length(v_ids, 1) >= 2 THEN
      v_name := public.gradebook_pluralize(public.gradebook_column_family_display_name(v_run->>'family'));
      FOR i IN 1 .. array_length(v_ids, 1) LOOP
        v_legacy := v_legacy || jsonb_build_object(v_ids[i]::text, jsonb_build_object('ids', to_jsonb(v_ids), 'name', v_name));
      END LOOP;
    END IF;
  END LOOP;

  SELECT COALESCE(array_agg(id ORDER BY id), '{}') INTO v_nulls
  FROM public.gradebook_columns
  WHERE gradebook_id = p_gradebook_id AND sort_order IS NULL;

  FOR r IN
    SELECT id, slug, sort_order
    FROM public.gradebook_columns
    WHERE gradebook_id = p_gradebook_id AND group_id IS NULL
    ORDER BY sort_order NULLS LAST, id
  LOOP
    v_before := v_legacy->(r.id::text);
    v_after := v_new_set->(r.id::text);
    v_reason := CASE
      WHEN r.sort_order IS NULL THEN 'null-sort-order'
      WHEN (SELECT COALESCE(jsonb_agg(x ORDER BY x), '[]') FROM jsonb_array_elements(COALESCE(v_before->'ids', '[]')) x)
           IS DISTINCT FROM
           (SELECT COALESCE(jsonb_agg(x ORDER BY x), '[]') FROM jsonb_array_elements(COALESCE(v_after->'ids', '[]')) x)
        THEN 'membership'
      WHEN (v_before->>'name') IS DISTINCT FROM (v_after->>'name') THEN 'name'
    END;
    IF v_reason IS NOT NULL THEN
      v_changes := v_changes || jsonb_build_array(jsonb_build_object(
        'column_id', r.id,
        'slug', r.slug,
        'reason', v_reason,
        'before', v_before->>'name',
        'after', v_after->>'name',
        -- How many columns share the header (1 = no header), so a gap merge reads as a size change.
        'before_size', COALESCE(jsonb_array_length(v_before->'ids'), 1),
        'after_size', COALESCE(jsonb_array_length(v_after->'ids'), 1)
      ));
    END IF;
  END LOOP;

  RETURN jsonb_build_object(
    'groups', v_groups,
    'null_sort_order_column_ids', to_jsonb(v_nulls),
    'changes', v_changes
  );
END;
$$;

REVOKE ALL ON FUNCTION public.gradebook_columns_auto_group_plan(bigint) FROM PUBLIC, anon, authenticated;

-- ---------------------------------------------------------------------------------------------
-- 6. Keeping groups contiguous
-- ---------------------------------------------------------------------------------------------

-- Pull every group's members up behind its first member (stable), then renumber sort_order
-- 0..n-1, but only if that changes anything. Internal: callers hold the gradebook lock.
CREATE OR REPLACE FUNCTION public.gradebook_columns_compact_groups(p_gradebook_id bigint)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  PERFORM set_config('pawtograder.bypass_sort_order_trigger_' || p_gradebook_id::text, 'true', true);

  WITH base AS (
    SELECT id, group_id, row_number() OVER (ORDER BY sort_order NULLS LAST, id) AS pos
    FROM public.gradebook_columns
    WHERE gradebook_id = p_gradebook_id
  ), anchored AS (
    SELECT id, pos,
      CASE WHEN group_id IS NULL THEN pos ELSE min(pos) OVER (PARTITION BY group_id) END AS anchor
    FROM base
  ), target AS (
    SELECT id, (row_number() OVER (ORDER BY anchor, pos) - 1)::integer AS new_order
    FROM anchored
  )
  UPDATE public.gradebook_columns gc
  SET sort_order = t.new_order
  FROM target t
  WHERE gc.id = t.id
    AND EXISTS (  -- renumber only when some column is out of place
      SELECT 1 FROM target t2 JOIN public.gradebook_columns g2 ON g2.id = t2.id
      WHERE g2.sort_order IS DISTINCT FROM t2.new_order
    )
    AND gc.sort_order IS DISTINCT FROM t.new_order;

  PERFORM set_config('pawtograder.bypass_sort_order_trigger_' || p_gradebook_id::text, 'false', true);
END;
$$;

REVOKE ALL ON FUNCTION public.gradebook_columns_compact_groups(bigint) FROM PUBLIC, anon, authenticated;


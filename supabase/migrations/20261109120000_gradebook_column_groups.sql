-- Turn groups on for a class: auto-group its gradebook if nothing is grouped yet (first enable),
-- then set the feature, in one transaction. Turning the feature off is a plain
-- merge_class_feature(..., false): groups are kept, so re-enabling needs no backfill.
CREATE OR REPLACE FUNCTION public.gradebook_enable_column_groups(p_class_id bigint)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_gradebook_id bigint;
  v_created integer := 0;
BEGIN
  IF NOT public.authorizeforclassinstructor(p_class_id) THEN
    RAISE EXCEPTION 'insufficient permissions: instructor access required for class %', p_class_id
      USING ERRCODE = '42501';
  END IF;

  SELECT gradebook_id INTO v_gradebook_id FROM public.classes WHERE id = p_class_id;
  IF v_gradebook_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.gradebook_columns WHERE gradebook_id = v_gradebook_id AND group_id IS NOT NULL
  ) THEN
    v_created := public.gradebook_columns_auto_group(v_gradebook_id);
  END IF;

  PERFORM public.merge_class_feature(p_class_id, 'gradebook-column-groups', true);
  RETURN v_created;
END;
$$;

REVOKE ALL ON FUNCTION public.gradebook_enable_column_groups(bigint) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.gradebook_enable_column_groups(bigint) TO authenticated, service_role;

-- Existing classes keep the legacy display until an instructor enables groups. Classes created
-- from here on have no entry, and the feature defaults to enabled (lib/courseFeatures.ts).
-- gradebook-topics is written here too, so both features roll out on the same terms.
UPDATE public.classes c
SET features = COALESCE(CASE WHEN jsonb_typeof(c.features) = 'array' THEN c.features END, '[]'::jsonb)
  || (
    SELECT COALESCE(jsonb_agg(jsonb_build_object('name', f, 'enabled', false)), '[]'::jsonb)
    FROM unnest(ARRAY['gradebook-column-groups', 'gradebook-topics']) AS f
    WHERE NOT EXISTS (
      SELECT 1
      FROM jsonb_array_elements(CASE WHEN jsonb_typeof(c.features) = 'array' THEN c.features ELSE '[]'::jsonb END) e
      WHERE e->>'name' = f
    )
  );

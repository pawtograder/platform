-- Staff get the row. Students get an id-only message and refetch through RLS, so the name of a
-- group they cannot see never reaches them.
CREATE OR REPLACE FUNCTION public.broadcast_gradebook_column_groups_change()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_class_id bigint;
  v_row_id bigint;
  v_payload jsonb;
BEGIN
  IF TG_OP = 'DELETE' THEN
    v_class_id := OLD.class_id;
    v_row_id := OLD.id;
  ELSE
    v_class_id := NEW.class_id;
    v_row_id := NEW.id;
  END IF;

  v_payload := jsonb_build_object(
    'type', 'table_change',
    'operation', TG_OP,
    'table', TG_TABLE_NAME,
    'row_id', v_row_id,
    'data', CASE WHEN TG_OP = 'DELETE' THEN to_jsonb(OLD) ELSE to_jsonb(NEW) END,
    'class_id', v_class_id,
    'target_audience', 'staff',
    'timestamp', now()
  );
  PERFORM public.safe_broadcast(v_payload, 'broadcast', 'class:' || v_class_id || ':staff', true);

  PERFORM public.safe_broadcast(
    v_payload || jsonb_build_object('data', NULL, 'target_audience', 'students'),
    'broadcast',
    'class:' || v_class_id || ':students',
    true
  );

  RETURN NULL;
END;
$$;

REVOKE ALL ON FUNCTION public.broadcast_gradebook_column_groups_change() FROM PUBLIC, anon, authenticated;


-- Family of a column under the legacy heuristic: "assignment-<type>" when the slug has three or
-- more parts and starts with "assignment", else the first part, else "other".
CREATE OR REPLACE FUNCTION public.gradebook_column_slug_family(p_slug text)
RETURNS text
LANGUAGE sql
IMMUTABLE
SET search_path = public, pg_temp
AS $$
  SELECT CASE
    WHEN split_part(COALESCE(p_slug, ''), '-', 1) = 'assignment'
         AND array_length(string_to_array(p_slug, '-'), 1) >= 3
      THEN 'assignment-' || split_part(p_slug, '-', 2)
    WHEN split_part(COALESCE(p_slug, ''), '-', 1) = '' THEN 'other'
    ELSE split_part(p_slug, '-', 1)
  END;
$$;

-- The legacy header text before pluralization: "Other", the capitalized sub-type of an
-- assignment family, or the capitalized prefix. Only the first character is upper-cased, as in
-- the browser.
CREATE OR REPLACE FUNCTION public.gradebook_column_family_display_name(p_family text)
RETURNS text
LANGUAGE sql
IMMUTABLE
SET search_path = public, pg_temp
AS $$
  SELECT CASE
    WHEN p_family = 'other' THEN 'Other'
    WHEN p_family LIKE 'assignment-%' THEN
      upper(left(split_part(p_family, '-', 2), 1)) || substr(split_part(p_family, '-', 2), 2)
    ELSE upper(left(p_family, 1)) || substr(p_family, 2)
  END;
$$;

-- The legacy header rendered pluralize(name). Stored names render verbatim, so auto-group stores
-- the plural. This covers the regular English rules plus the cases seen in real gradebooks; the
-- preview shows every name before anything is written.
CREATE OR REPLACE FUNCTION public.gradebook_pluralize(p_text text)
RETURNS text
LANGUAGE plpgsql
IMMUTABLE
SET search_path = public, pg_temp
AS $$
DECLARE
  v_head text;
  v_word text;
  v_lower text;
  v_suffix text;
  v_upper boolean;
BEGIN
  IF p_text IS NULL OR btrim(p_text) = '' THEN
    RETURN p_text;
  END IF;
  v_head := COALESCE(substring(p_text FROM '^(.*\s)\S+$'), '');
  v_word := substring(p_text FROM '(\S+)$');
  v_lower := lower(v_word);
  v_upper := v_word = upper(v_word) AND v_word <> lower(v_word) AND length(v_word) > 1;

  IF v_lower IN ('homework', 'feedback', 'participation', 'attendance', 'information', 'equipment', 'other')
     AND v_lower <> 'other' THEN
    RETURN p_text;
  ELSIF v_lower ~ 's$' AND v_lower !~ '(ss|us|is)$' THEN
    RETURN p_text;
  ELSIF v_lower ~ 'quiz$' THEN
    v_suffix := 'zes';
  ELSIF v_lower ~ '(s|x|z|ch|sh)$' THEN
    v_suffix := 'es';
  ELSIF v_lower ~ '[^aeiou]y$' THEN
    v_word := left(v_word, length(v_word) - 1);
    v_suffix := 'ies';
  ELSE
    v_suffix := 's';
  END IF;

  RETURN v_head || v_word || CASE WHEN v_upper THEN upper(v_suffix) ELSE v_suffix END;
END;
$$;

-- Longest common whitespace-token prefix of a set of names, with trailing tokens that carry no
-- letters ("1", "#2", "-") removed and trailing separators trimmed. NULL when there is none.
CREATE OR REPLACE FUNCTION public.gradebook_common_name_prefix(p_names text[])
RETURNS text
LANGUAGE plpgsql
IMMUTABLE
SET search_path = public, pg_temp
AS $$
DECLARE
  v_tokens text[];
  v_other text[];
  v_len integer;
  v_name text;
  i integer;
BEGIN
  IF p_names IS NULL OR array_length(p_names, 1) IS NULL THEN
    RETURN NULL;
  END IF;
  v_tokens := regexp_split_to_array(btrim(COALESCE(p_names[1], '')), '\s+');
  v_len := COALESCE(array_length(v_tokens, 1), 0);
  FOREACH v_name IN ARRAY p_names LOOP
    v_other := regexp_split_to_array(btrim(COALESCE(v_name, '')), '\s+');
    i := 0;
    WHILE i < v_len AND i < COALESCE(array_length(v_other, 1), 0) AND v_tokens[i + 1] = v_other[i + 1] LOOP
      i := i + 1;
    END LOOP;
    v_len := i;
  END LOOP;
  WHILE v_len > 0 AND v_tokens[v_len] !~ '[[:alpha:]]' LOOP
    v_len := v_len - 1;
  END LOOP;
  IF v_len = 0 THEN
    RETURN NULL;
  END IF;
  RETURN NULLIF(regexp_replace(array_to_string(v_tokens[1:v_len], ' '), '[\s:#\-–—,.(]+$', ''), '');
END;
$$;


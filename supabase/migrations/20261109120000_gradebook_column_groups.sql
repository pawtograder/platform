-- Resolve a gradebook's class and require an instructor (or the service role).
CREATE OR REPLACE FUNCTION public.gradebook_require_instructor(p_gradebook_id bigint)
RETURNS bigint
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_class_id bigint;
BEGIN
  SELECT class_id INTO v_class_id FROM public.gradebooks WHERE id = p_gradebook_id;
  IF v_class_id IS NULL THEN
    RAISE EXCEPTION 'gradebook % not found', p_gradebook_id USING ERRCODE = 'P0002';
  END IF;
  IF auth.role() IS DISTINCT FROM 'service_role' AND NOT public.authorizeforclassinstructor(v_class_id) THEN
    RAISE EXCEPTION 'insufficient permissions: instructor access required for class %', v_class_id
      USING ERRCODE = '42501';
  END IF;
  RETURN v_class_id;
END;
$$;


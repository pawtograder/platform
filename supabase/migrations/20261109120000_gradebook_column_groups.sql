    RAISE EXCEPTION 'Columns must all belong to gradebook %', p_gradebook_id USING ERRCODE = '22023';
  END IF;

  INSERT INTO public.gradebook_column_groups (class_id, gradebook_id, name)
  VALUES (v_class_id, p_gradebook_id, btrim(p_name))
  RETURNING id INTO v_group_id;

  PERFORM public.gradebook_columns_set_group(p_column_ids, v_group_id);
  RETURN v_group_id;
END;
$$;


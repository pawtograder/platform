-- First-class gradebook column groups.
--
-- Until now a "group" existed only as a render-time heuristic in the browser (split the slug on
-- '-', take a prefix, break the run where sort_order is not +1). This migration makes a group a
-- row, puts membership on gradebook_columns.group_id, and gates the new behaviour behind the
-- `gradebook-column-groups` course feature.
--
-- Rollout: every class that exists when this runs gets the feature written as disabled, so its
-- gradebook keeps rendering through the legacy heuristic and no column is touched here. Classes
-- created afterwards have no entry and default to enabled. An instructor enables an existing
-- class from the Feature flags page, which previews and then applies the auto-group rule
-- (gradebook_enable_column_groups).
--
-- Design record: docs/adr/gradebook-column-groups-and-topics.md (CS 4535 bake-off, Fall 2026).
-- Down path: 20261109120000_gradebook_column_groups.down.sql.txt (not applied by the CLI).

-- ---------------------------------------------------------------------------------------------
-- 1. Schema
-- ---------------------------------------------------------------------------------------------

-- Target for the group's (gradebook_id, class_id) foreign key, which pins a group's class to
-- its gradebook's class.
ALTER TABLE public.gradebooks
  ADD CONSTRAINT gradebooks_id_class_id_key UNIQUE (id, class_id);

CREATE TABLE public.gradebook_column_groups (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  class_id bigint NOT NULL,
  gradebook_id bigint NOT NULL,
  name text NOT NULL,
  CONSTRAINT gradebook_column_groups_name_not_blank CHECK (btrim(name) <> ''),
  -- Target for gradebook_columns' composite FK: a column can only join a group of its own gradebook.
  CONSTRAINT gradebook_column_groups_id_gradebook_id_key UNIQUE (id, gradebook_id),
  CONSTRAINT gradebook_column_groups_gradebook_class_fkey
    FOREIGN KEY (gradebook_id, class_id) REFERENCES public.gradebooks (id, class_id) ON DELETE CASCADE
);

COMMENT ON TABLE public.gradebook_column_groups IS
  'A named, collapsible run of gradebook columns. Membership is gradebook_columns.group_id; a group is drawn at the position of its first member and has no order of its own.';

-- Same-name groups used to share collapse state; names are unique per gradebook, ignoring case.
CREATE UNIQUE INDEX gradebook_column_groups_gradebook_lower_name_key
  ON public.gradebook_column_groups (gradebook_id, lower(name));
CREATE INDEX gradebook_column_groups_class_id_idx ON public.gradebook_column_groups (class_id);

ALTER TABLE public.gradebook_columns ADD COLUMN group_id bigint;

-- Deleting a group ungroups its columns and never touches grades. The column list on SET NULL
-- keeps gradebook_id intact.
ALTER TABLE public.gradebook_columns
  ADD CONSTRAINT gradebook_columns_group_fkey
  FOREIGN KEY (group_id, gradebook_id) REFERENCES public.gradebook_column_groups (id, gradebook_id)
  ON DELETE SET NULL (group_id);

CREATE INDEX gradebook_columns_group_id_idx ON public.gradebook_columns (group_id) WHERE group_id IS NOT NULL;

COMMENT ON COLUMN public.gradebook_columns.group_id IS
  'Display group (gradebook_column_groups). NULL = ungrouped. Only read when the course has the gradebook-column-groups feature enabled.';

CREATE TRIGGER set_updated_at_on_gradebook_column_groups
  BEFORE UPDATE ON public.gradebook_column_groups
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();


-- Move columns into a group (or out of every group, when p_group_id is NULL) and place them so
-- the group stays contiguous:
--   into a group with other members  -> right after its last remaining member
--   into an empty (new) group        -> where the first of them already is
--   out of a group                   -> right after the run they left
CREATE OR REPLACE FUNCTION public.gradebook_columns_set_group(p_column_ids bigint[], p_group_id bigint)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_gradebook_id bigint;
  v_count integer;
  v_order bigint[];
  v_moving bigint[];
  v_rest bigint[];
  v_anchor bigint;
  v_idx integer;
BEGIN
  IF COALESCE(array_length(p_column_ids, 1), 0) = 0 THEN
    RETURN;
  END IF;

  SELECT min(gradebook_id), count(DISTINCT gradebook_id), count(*)
  INTO v_gradebook_id, v_idx, v_count
  FROM public.gradebook_columns WHERE id = ANY (p_column_ids);
  IF v_count <> (SELECT count(DISTINCT x) FROM unnest(p_column_ids) x) THEN
    RAISE EXCEPTION 'One or more gradebook columns not found' USING ERRCODE = 'P0002';
  END IF;
  IF v_idx <> 1 THEN
    RAISE EXCEPTION 'Columns must all belong to one gradebook' USING ERRCODE = '22023';
  END IF;

  PERFORM public.gradebook_require_instructor(v_gradebook_id);
  PERFORM pg_advisory_xact_lock(v_gradebook_id);

  IF p_group_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.gradebook_column_groups WHERE id = p_group_id AND gradebook_id = v_gradebook_id
  ) THEN
    RAISE EXCEPTION 'Group % is not in this gradebook', p_group_id USING ERRCODE = '22023';
  END IF;

  -- Current display order, with the moving columns in their current relative order.
  SELECT array_agg(id ORDER BY sort_order NULLS LAST, id) INTO v_order
  FROM public.gradebook_columns WHERE gradebook_id = v_gradebook_id;
  SELECT array_agg(x ORDER BY array_position(v_order, x)) INTO v_moving FROM unnest(p_column_ids) x;
  SELECT array_agg(x ORDER BY ord) INTO v_rest
  FROM unnest(v_order) WITH ORDINALITY AS t(x, ord) WHERE x <> ALL (v_moving);
  v_rest := COALESCE(v_rest, '{}');

  IF p_group_id IS NOT NULL THEN
    -- Last remaining member of the target group, if any.
    SELECT x INTO v_anchor FROM unnest(v_rest) WITH ORDINALITY AS t(x, ord)
    JOIN public.gradebook_columns gc ON gc.id = t.x AND gc.group_id = p_group_id
    ORDER BY ord DESC LIMIT 1;
  ELSE
    -- Last column of the run the first moving column leaves.
    SELECT x INTO v_anchor FROM unnest(v_rest) WITH ORDINALITY AS t(x, ord)
    JOIN public.gradebook_columns gc ON gc.id = t.x
    WHERE gc.group_id IS NOT NULL
      AND gc.group_id = (SELECT group_id FROM public.gradebook_columns WHERE id = v_moving[1])
    ORDER BY ord DESC LIMIT 1;
  END IF;

  IF v_anchor IS NOT NULL THEN
    v_idx := array_position(v_rest, v_anchor);
    v_order := v_rest[1:v_idx] || v_moving || v_rest[v_idx + 1:];
  ELSE
    -- Keep the block where its first member is.
    v_idx := array_position(v_order, v_moving[1]);
    v_order := (SELECT COALESCE(array_agg(x ORDER BY ord), '{}') FROM unnest(v_order[1:v_idx - 1]) WITH ORDINALITY t(x, ord) WHERE x <> ALL (v_moving))
               || v_moving
               || (SELECT COALESCE(array_agg(x ORDER BY ord), '{}') FROM unnest(v_order[v_idx:]) WITH ORDINALITY t(x, ord) WHERE x <> ALL (v_moving));
  END IF;

  UPDATE public.gradebook_columns SET group_id = p_group_id
  WHERE id = ANY (v_moving) AND group_id IS DISTINCT FROM p_group_id;

  PERFORM set_config('pawtograder.bypass_sort_order_trigger_' || v_gradebook_id::text, 'true', true);
  UPDATE public.gradebook_columns gc
  SET sort_order = o.new_order
  FROM (SELECT x AS id, (ord - 1)::integer AS new_order FROM unnest(v_order) WITH ORDINALITY t(x, ord)) o
  WHERE gc.id = o.id AND gc.sort_order IS DISTINCT FROM o.new_order;
  PERFORM set_config('pawtograder.bypass_sort_order_trigger_' || v_gradebook_id::text, 'false', true);

  PERFORM public.gradebook_columns_compact_groups(v_gradebook_id);
END;
$$;

REVOKE ALL ON FUNCTION public.gradebook_columns_set_group(bigint[], bigint) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.gradebook_columns_set_group(bigint[], bigint) TO authenticated, service_role;

CREATE OR REPLACE FUNCTION public.gradebook_column_group_create(p_gradebook_id bigint, p_name text, p_column_ids bigint[])
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_class_id bigint;
  v_group_id bigint;
BEGIN
  v_class_id := public.gradebook_require_instructor(p_gradebook_id);
  IF COALESCE(array_length(p_column_ids, 1), 0) = 0 THEN
    RAISE EXCEPTION 'A group needs at least one column' USING ERRCODE = '22023';
  END IF;
  IF EXISTS (SELECT 1 FROM unnest(p_column_ids) x WHERE NOT EXISTS (
    SELECT 1 FROM public.gradebook_columns gc WHERE gc.id = x AND gc.gradebook_id = p_gradebook_id

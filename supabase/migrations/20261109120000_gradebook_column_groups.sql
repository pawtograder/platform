-- Apply the plan. Membership is written with one UPDATE per group: every column update fans out
-- one realtime message per student (broadcast_gradebook_columns_change).
CREATE OR REPLACE FUNCTION public.gradebook_columns_auto_group(p_gradebook_id bigint)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_class_id bigint;
  v_plan jsonb;
  v_group jsonb;
  v_group_id bigint;
  v_ids bigint[];
  v_created integer := 0;
BEGIN
  v_class_id := public.gradebook_require_instructor(p_gradebook_id);
  PERFORM pg_advisory_xact_lock(p_gradebook_id);

  v_plan := public.gradebook_columns_auto_group_plan(p_gradebook_id);

  IF jsonb_array_length(v_plan->'null_sort_order_column_ids') > 0 THEN
    PERFORM set_config('pawtograder.bypass_sort_order_trigger_' || p_gradebook_id::text, 'true', true);
    UPDATE public.gradebook_columns gc
    SET sort_order = base.max_so + t.ord::integer
    FROM (SELECT COALESCE(max(sort_order), -1) AS max_so FROM public.gradebook_columns WHERE gradebook_id = p_gradebook_id) base,
         jsonb_array_elements_text(v_plan->'null_sort_order_column_ids') WITH ORDINALITY AS t(id, ord)
    WHERE gc.id = t.id::bigint;
    PERFORM set_config('pawtograder.bypass_sort_order_trigger_' || p_gradebook_id::text, 'false', true);
  END IF;

  FOR v_group IN SELECT value FROM jsonb_array_elements(v_plan->'groups') LOOP
    SELECT array_agg(value::bigint) INTO v_ids FROM jsonb_array_elements_text(v_group->'column_ids');
    INSERT INTO public.gradebook_column_groups (class_id, gradebook_id, name)
    VALUES (v_class_id, p_gradebook_id, v_group->>'name')
    RETURNING id INTO v_group_id;
    UPDATE public.gradebook_columns SET group_id = v_group_id WHERE id = ANY (v_ids);
    v_created := v_created + 1;
  END LOOP;

  PERFORM public.gradebook_columns_compact_groups(p_gradebook_id);
  RETURN v_created;
END;
$$;

REVOKE ALL ON FUNCTION public.gradebook_columns_auto_group(bigint) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.gradebook_columns_auto_group(bigint) TO authenticated, service_role;


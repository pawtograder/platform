-- Staff see every group in their class. Students see a group only when it has at least one
-- column they can see, using exactly the predicate of "everyone in class can view" on
-- gradebook_columns, so a group made only of instructor-only columns does not leak its name.
CREATE POLICY "staff and students with a visible member can view"
ON public.gradebook_column_groups
FOR SELECT
TO authenticated
USING (
  EXISTS (
    SELECT 1
    FROM public.user_privileges up
    WHERE up.user_id = (SELECT auth.uid())
      AND up.class_id = gradebook_column_groups.class_id
  )
  AND (
    EXISTS (
      SELECT 1
      FROM public.user_privileges up2
      WHERE up2.user_id = (SELECT auth.uid())
        AND up2.class_id = gradebook_column_groups.class_id
        AND up2.role IN ('instructor', 'grader')
    )
    OR EXISTS (
      SELECT 1
      FROM public.gradebook_columns gc
      WHERE gc.group_id = gradebook_column_groups.id
        AND (COALESCE(gc.instructor_only, false) = false OR gc.released = true)
    )
  )
);

CREATE POLICY "instructors rename"
ON public.gradebook_column_groups
FOR UPDATE
TO authenticated
USING (public.authorizeforclassinstructor(class_id))
WITH CHECK (public.authorizeforclassinstructor(class_id));

CREATE POLICY "instructors delete"
ON public.gradebook_column_groups
FOR DELETE
TO authenticated
USING (public.authorizeforclassinstructor(class_id));


CREATE POLICY "Authenticated users can read capabilities" ON public.capabilities
  FOR SELECT TO authenticated
  USING (true);

CREATE POLICY "Class members can read their class roles" ON public.class_roles
  FOR SELECT TO authenticated
  USING (class_id IN (SELECT up.class_id FROM public.user_privileges up WHERE up.user_id = (SELECT auth.uid())));

CREATE POLICY "Class members can read their class role capabilities" ON public.role_capabilities
  FOR SELECT TO authenticated
  USING (role_id IN (
    SELECT cr.id FROM public.class_roles cr
    WHERE cr.class_id IN (SELECT up.class_id FROM public.user_privileges up WHERE up.user_id = (SELECT auth.uid()))
  ));

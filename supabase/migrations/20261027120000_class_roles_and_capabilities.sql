  ALTER COLUMN class_role_id SET NOT NULL,
  ADD CONSTRAINT user_roles_class_role_fkey
    FOREIGN KEY (class_role_id, class_id) REFERENCES public.class_roles (id, class_id);

CREATE INDEX idx_user_roles_class_role_id ON public.user_roles (class_role_id);

-- Placeholder default, so generated types make class_role_id optional on INSERT: the trigger
-- below always replaces it, and NOT NULL is checked after BEFORE triggers run. plpgsql so the
-- planner can't fold it into a NULL constant, which Postgres would not store as a default.
CREATE OR REPLACE FUNCTION public.user_roles_class_role_id_placeholder()
RETURNS bigint
LANGUAGE plpgsql
AS $$
BEGIN
  RETURN NULL;
END;
$$;

ALTER TABLE public.user_roles
  ALTER COLUMN class_role_id SET DEFAULT public.user_roles_class_role_id_placeholder();

-- Fill class_role_id from the class's default role. On UPDATE, a user still on the default
-- role for their old app_role follows the new app_role; a custom role is kept.
CREATE OR REPLACE FUNCTION public.user_roles_set_default_class_role()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NEW.class_role_id IS NULL
     OR (TG_OP = 'UPDATE'
         AND NEW.class_role_id IS NOT DISTINCT FROM OLD.class_role_id
         AND (NEW.role IS DISTINCT FROM OLD.role OR NEW.class_id IS DISTINCT FROM OLD.class_id)
         AND EXISTS (
           SELECT 1 FROM public.class_roles cr
           WHERE cr.id = OLD.class_role_id AND cr.default_for IS NOT NULL
         ))
  THEN
    SELECT cr.id INTO NEW.class_role_id
    FROM public.class_roles cr
    WHERE cr.class_id = NEW.class_id
      AND cr.default_for = NEW.role;

    IF NEW.class_role_id IS NULL THEN
      RAISE EXCEPTION 'class % has no default class role for app_role %', NEW.class_id, NEW.role;
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.user_roles_set_default_class_role() FROM PUBLIC, anon, authenticated;

CREATE TRIGGER trg_user_roles_set_default_class_role
BEFORE INSERT OR UPDATE OF role, class_id, class_role_id ON public.user_roles
FOR EACH ROW EXECUTE FUNCTION public.user_roles_set_default_class_role();

-- ---------------------------------------------------------------------------
-- user_privileges.class_role_id
-- ---------------------------------------------------------------------------

ALTER TABLE public.user_privileges ADD COLUMN class_role_id bigint;

UPDATE public.user_privileges up
SET class_role_id = ur.class_role_id
FROM public.user_roles ur
WHERE ur.user_id = up.user_id
  AND ur.class_id = up.class_id
  AND ur.role = up.role
  AND ur.disabled = false;

CREATE INDEX idx_user_privileges_class_role ON public.user_privileges (user_id, class_role_id);

-- Same as 20250916200614_tweak-gradebook-recalc-frequency.sql, plus class_role_id.
CREATE OR REPLACE FUNCTION public.user_privileges_sync_from_user_roles() RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER SET search_path = 'public'
AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF NEW.disabled = false THEN
      INSERT INTO public.user_privileges(user_id, class_id, role, private_profile_id, public_profile_id, class_role_id)
      VALUES (NEW.user_id, NEW.class_id, NEW.role, NEW.private_profile_id, NEW.public_profile_id, NEW.class_role_id)
      ON CONFLICT (user_id, class_id) DO UPDATE SET
        role = EXCLUDED.role,
        private_profile_id = EXCLUDED.private_profile_id,
        public_profile_id = EXCLUDED.public_profile_id,
        class_role_id = EXCLUDED.class_role_id;
    END IF;
    RETURN NEW;
  ELSIF TG_OP = 'UPDATE' THEN
    -- Ensure NEW active role exists
    IF NEW.disabled = false THEN
      INSERT INTO public.user_privileges(user_id, class_id, role, private_profile_id, public_profile_id, class_role_id)
      VALUES (NEW.user_id, NEW.class_id, NEW.role, NEW.private_profile_id, NEW.public_profile_id, NEW.class_role_id)
      ON CONFLICT (user_id, class_id) DO UPDATE SET
        role = EXCLUDED.role,
        private_profile_id = EXCLUDED.private_profile_id,
        public_profile_id = EXCLUDED.public_profile_id,
        class_role_id = EXCLUDED.class_role_id;
    END IF;

    -- Remove OLD role if no longer present in any active row
    IF OLD.disabled = false AND (OLD.user_id IS DISTINCT FROM NEW.user_id OR OLD.role IS DISTINCT FROM NEW.role OR OLD.class_id IS DISTINCT FROM NEW.class_id OR NEW.disabled = true) THEN
      IF NOT EXISTS (
        SELECT 1 FROM public.user_roles r
        WHERE r.user_id = OLD.user_id AND r.class_id = OLD.class_id AND r.role = OLD.role AND r.disabled = false
      ) THEN
        DELETE FROM public.user_privileges up
        WHERE up.user_id = OLD.user_id AND up.class_id = OLD.class_id AND up.role = OLD.role;
      END IF;
    END IF;
    RETURN NEW;
  ELSIF TG_OP = 'DELETE' THEN
    IF OLD.disabled = false THEN
      IF NOT EXISTS (
        SELECT 1 FROM public.user_roles r
        WHERE r.user_id = OLD.user_id AND r.class_id = OLD.class_id AND r.role = OLD.role AND r.disabled = false
      ) THEN
        DELETE FROM public.user_privileges up
        WHERE up.user_id = OLD.user_id AND up.class_id = OLD.class_id AND up.role = OLD.role;
      END IF;
    END IF;
    RETURN OLD;
  END IF;
  RETURN NULL;
END;$$;

DROP TRIGGER IF EXISTS trg_user_priv_sync_upd ON public.user_roles;
CREATE TRIGGER trg_user_priv_sync_upd
AFTER UPDATE OF user_id, role, disabled, class_role_id ON public.user_roles
FOR EACH ROW EXECUTE FUNCTION public.user_privileges_sync_from_user_roles();


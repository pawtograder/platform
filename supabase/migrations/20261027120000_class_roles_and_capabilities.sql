-- Capability model foundation (#1010, step 1).
--
-- The UI and RLS decide permissions separately today, so graders see controls the database
-- then refuses (#983, #996, #1010). This adds per-class roles made of capabilities, which both
-- sides will read:
--   * capabilities       every capability that exists (one row per action, added by migrations);
--   * class_roles        each class's roles; seeded defaults carry default_for = their app_role;
--   * role_capabilities  which capabilities each role has;
--   * user_roles.class_role_id  each user's one role in each class, copied to user_privileges.
--
-- Every class gets default instructor, grader, student and admin roles. Only instructor gets the
-- four capabilities below, which matches today: each of those actions is instructor-only. app_role
-- stays as basic membership, and class_role_id follows it: a BEFORE trigger fills it from the
-- class's default role, so existing insert paths (enrollment, invitations, SIS sync) need no
-- change. 'admin' rows get the admin role, with no capabilities: authorizeforclassinstructor
-- checks role = 'instructor' only, so a class admin can't do these actions today either.
--
-- Nothing reads these tables yet, so no behavior changes. Writes are default-denied by RLS;
-- the roles page will add write policies. Policies that check a capability must keep the inline
-- shape `class_id IN (SELECT up.class_id FROM user_privileges up JOIN role_capabilities ...)`,
-- since a helper function with a subquery can't be inlined and runs once per row.

-- ---------------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------------

CREATE TABLE public.capabilities (
  name text PRIMARY KEY,
  description text NOT NULL
);

INSERT INTO public.capabilities (name, description) VALUES
  ('manage_review_assignments', 'Create, edit, delete and clear review assignments'),
  ('publish_groups', 'Publish group changes on Manage Groups'),
  ('manage_assignments', 'Create and edit assignments'),
  ('manage_roles', 'Create class roles, choose their capabilities, and assign them to people');

CREATE TABLE public.class_roles (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  class_id bigint NOT NULL REFERENCES public.classes (id) ON DELETE CASCADE,
  name text NOT NULL,
  default_for public.app_role,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT class_roles_class_name_key UNIQUE (class_id, name),
  CONSTRAINT class_roles_class_default_key UNIQUE (class_id, default_for),
  -- Target of the composite FK from user_roles, so a user can't hold another class's role.
  CONSTRAINT class_roles_id_class_key UNIQUE (id, class_id)
);

COMMENT ON COLUMN public.class_roles.default_for IS
  'Set on the seeded default role for this app_role; new user_roles rows get it. NULL for custom roles.';

CREATE TABLE public.role_capabilities (
  role_id bigint NOT NULL REFERENCES public.class_roles (id) ON DELETE CASCADE,
  capability text NOT NULL REFERENCES public.capabilities (name),
  PRIMARY KEY (role_id, capability)
);

CREATE INDEX idx_role_capabilities_capability ON public.role_capabilities (capability, role_id);

-- ---------------------------------------------------------------------------
-- Default roles
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.seed_default_class_roles(p_class_id bigint)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  INSERT INTO public.class_roles (class_id, name, default_for)
  VALUES
    (p_class_id, 'instructor', 'instructor'),
    (p_class_id, 'grader', 'grader'),
    (p_class_id, 'student', 'student'),
    (p_class_id, 'admin', 'admin')
  ON CONFLICT DO NOTHING;

  INSERT INTO public.role_capabilities (role_id, capability)
  SELECT cr.id, c.name
  FROM public.class_roles cr
  CROSS JOIN public.capabilities c
  WHERE cr.class_id = p_class_id AND cr.default_for = 'instructor'
  ON CONFLICT DO NOTHING;
END;
$$;

REVOKE ALL ON FUNCTION public.seed_default_class_roles(bigint) FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.classes_seed_default_class_roles()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  PERFORM public.seed_default_class_roles(NEW.id);
  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.classes_seed_default_class_roles() FROM PUBLIC, anon, authenticated;

CREATE TRIGGER trg_classes_seed_default_class_roles
AFTER INSERT ON public.classes
FOR EACH ROW EXECUTE FUNCTION public.classes_seed_default_class_roles();

SELECT public.seed_default_class_roles(id) FROM public.classes;


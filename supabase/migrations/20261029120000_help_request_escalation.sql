CREATE OR REPLACE FUNCTION public.help_request_caller_profile(p_class_id bigint)
RETURNS uuid
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $$
  SELECT ur.private_profile_id
    FROM public.user_roles ur
   WHERE ur.user_id = auth.uid()
     AND ur.class_id = p_class_id
     AND ur.disabled = false
   LIMIT 1;
$$;

REVOKE ALL ON FUNCTION public.help_request_caller_profile(bigint) FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.log_help_request_activity(
  p_help_request_id bigint,
  p_class_id bigint,
  p_activity_type public.student_help_activity_type,
  p_description text
)
RETURNS void
LANGUAGE sql
SECURITY DEFINER
SET search_path TO ''
AS $$
  INSERT INTO public.student_help_activity (student_profile_id, class_id, help_request_id, activity_type, activity_description)
  SELECT hrs.profile_id, p_class_id, p_help_request_id, p_activity_type, p_description
    FROM public.help_request_students hrs
   WHERE hrs.help_request_id = p_help_request_id;
$$;

REVOKE ALL ON FUNCTION public.log_help_request_activity(bigint, bigint, public.student_help_activity_type, text) FROM PUBLIC, anon, authenticated;

-- ---------------------------------------------------------------------------
-- escalate_help_request: the assigned TA hands off mid-help
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.escalate_help_request(p_help_request_id bigint, p_note text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $$
DECLARE
  v_request public.help_requests%ROWTYPE;
  v_caller uuid;
  v_note text := btrim(coalesce(p_note, ''));
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'not authenticated' USING ERRCODE = '28000';
  END IF;
  IF char_length(v_note) NOT BETWEEN 1 AND 500 THEN
    RAISE EXCEPTION 'an escalation note of 1 to 500 characters is required' USING ERRCODE = '22023';
  END IF;

  SELECT * INTO v_request FROM public.help_requests WHERE id = p_help_request_id FOR UPDATE;
  IF NOT FOUND OR NOT public.authorizeforhelprequeststaff(v_request.class_id) THEN
    RAISE EXCEPTION 'help request % not found', p_help_request_id USING ERRCODE = '42501';
  END IF;

  v_caller := public.help_request_caller_profile(v_request.class_id);
  IF v_request.status <> 'in_progress' OR v_request.assignee IS DISTINCT FROM v_caller THEN
    RAISE EXCEPTION 'only the staff member currently helping can escalate this request' USING ERRCODE = '42501';
  END IF;

  PERFORM set_config('pawtograder.help_request_escalation_rpc', 'on', true);

  INSERT INTO public.help_request_escalations (class_id, help_request_id, escalated_by, source, previous_assignee, note)
  VALUES (v_request.class_id, v_request.id, v_caller, 'staff', v_request.assignee, v_note);

  -- Clearing the assignee ends the work session (trigger_help_request_work_sessions).
  UPDATE public.help_requests
     SET status = 'open',
         assignee = NULL,
         escalation_count = escalation_count + 1,
         last_escalated_at = now(),
         check_in_expires_at = NULL
   WHERE id = v_request.id;

  PERFORM public.log_help_request_activity(v_request.id, v_request.class_id, 'request_escalated', 'Request escalated by staff');

  PERFORM set_config('pawtograder.help_request_escalation_rpc', 'off', true);
END;
$$;

REVOKE ALL ON FUNCTION public.escalate_help_request(bigint, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.escalate_help_request(bigint, text) TO authenticated, service_role;

-- ---------------------------------------------------------------------------
-- finish_help_request: staff Resolve (opens the check-in) or End ticket (final)
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.finish_help_request(p_help_request_id bigint, p_end_ticket boolean DEFAULT false)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $$
DECLARE
  v_request public.help_requests%ROWTYPE;
  v_caller uuid;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'not authenticated' USING ERRCODE = '28000';
  END IF;

  SELECT * INTO v_request FROM public.help_requests WHERE id = p_help_request_id FOR UPDATE;
  IF NOT FOUND OR NOT public.authorizeforhelprequeststaff(v_request.class_id) THEN
    RAISE EXCEPTION 'help request % not found', p_help_request_id USING ERRCODE = '42501';
  END IF;

  -- Resolve applies to active tickets. End ticket also applies to a resolved ticket whose
  -- check-in is still pending, so staff can withdraw the student's option to escalate.
  IF NOT (v_request.status IN ('open', 'in_progress')
          OR (p_end_ticket AND v_request.status = 'resolved')) THEN
    RAISE EXCEPTION 'help request % is already finished', p_help_request_id USING ERRCODE = '22023';
  END IF;

  v_caller := public.help_request_caller_profile(v_request.class_id);

  PERFORM set_config('pawtograder.help_request_escalation_rpc', 'on', true);

  UPDATE public.help_requests
     SET status = CASE WHEN p_end_ticket THEN 'closed'::public.help_request_status ELSE 'resolved'::public.help_request_status END,
         resolved_by = coalesce(CASE WHEN v_request.status = 'resolved' THEN resolved_by END, v_caller),
         resolved_at = coalesce(CASE WHEN v_request.status = 'resolved' THEN resolved_at END, now()),
         check_in_expires_at = CASE WHEN p_end_ticket THEN NULL ELSE now() + interval '10 minutes' END
   WHERE id = v_request.id;

  PERFORM public.log_help_request_activity(
    v_request.id, v_request.class_id, 'request_resolved',
    CASE WHEN p_end_ticket THEN 'Request ended by staff' ELSE 'Request resolved by staff' END);

  PERFORM set_config('pawtograder.help_request_escalation_rpc', 'off', true);
END;
$$;

REVOKE ALL ON FUNCTION public.finish_help_request(bigint, boolean) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.finish_help_request(bigint, boolean) TO authenticated, service_role;

-- ---------------------------------------------------------------------------
-- answer_help_request_check_in: the student's "Did your problem get fixed?"
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.answer_help_request_check_in(
  p_help_request_id bigint,
  p_fixed boolean,
  p_note text DEFAULT NULL
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $$
DECLARE
  v_request public.help_requests%ROWTYPE;
  v_caller uuid;
  v_previous_assignee uuid;
  v_note text := btrim(coalesce(p_note, ''));
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'not authenticated' USING ERRCODE = '28000';
  END IF;

  -- The row lock serializes answers from students sharing a group request: the first wins,
  -- and the second sees the check-in already cleared.
  SELECT * INTO v_request FROM public.help_requests WHERE id = p_help_request_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'help request % not found', p_help_request_id USING ERRCODE = '42501';
  END IF;

  v_caller := public.help_request_caller_profile(v_request.class_id);
  IF v_caller IS NULL OR NOT EXISTS (
       SELECT 1 FROM public.help_request_students hrs
        WHERE hrs.help_request_id = v_request.id AND hrs.profile_id = v_caller) THEN
    RAISE EXCEPTION 'help request % not found', p_help_request_id USING ERRCODE = '42501';
  END IF;

  IF v_request.status <> 'resolved'
     OR v_request.check_in_expires_at IS NULL
     OR v_request.check_in_expires_at <= now() THEN
    RAISE EXCEPTION 'this help request is no longer waiting for a check-in' USING ERRCODE = '22023';
  END IF;

  IF NOT p_fixed AND char_length(v_note) NOT BETWEEN 1 AND 500 THEN
    RAISE EXCEPTION 'an escalation note of 1 to 500 characters is required' USING ERRCODE = '22023';
  END IF;

  PERFORM set_config('pawtograder.help_request_escalation_rpc', 'on', true);

  IF p_fixed THEN
    UPDATE public.help_requests SET check_in_expires_at = NULL WHERE id = v_request.id;
  ELSE
    SELECT coalesce(v_request.assignee, (
             SELECT ws.ta_profile_id FROM public.help_request_work_sessions ws
              WHERE ws.help_request_id = v_request.id
              ORDER BY ws.started_at DESC LIMIT 1))
      INTO v_previous_assignee;

    INSERT INTO public.help_request_escalations (class_id, help_request_id, escalated_by, source, previous_assignee, note)
    VALUES (v_request.class_id, v_request.id, v_caller, 'student', v_previous_assignee, v_note);

    UPDATE public.help_requests
       SET status = 'open',
           assignee = NULL,
           resolved_by = NULL,
           resolved_at = NULL,
           resolution_status = NULL,
           resolution_notes = NULL,
           check_in_expires_at = NULL,
           escalation_count = escalation_count + 1,
           last_escalated_at = now()
     WHERE id = v_request.id;

    PERFORM public.log_help_request_activity(v_request.id, v_request.class_id, 'request_escalated', 'Request escalated by student after check-in');
  END IF;

  PERFORM set_config('pawtograder.help_request_escalation_rpc', 'off', true);
END;
$$;

REVOKE ALL ON FUNCTION public.answer_help_request_check_in(bigint, boolean, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.answer_help_request_check_in(bigint, boolean, text) TO authenticated, service_role;

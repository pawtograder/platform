-- Office hours ticket escalation (docs/prd-oh-escalation.md).
--
-- A ticket that a TA could not finish goes back to the queue flagged, ahead of
-- normal tickets, with a note for whoever picks it up next. Two ways in:
--   * staff: the assigned TA escalates mid-help (escalate_help_request);
--   * student: after staff press Resolve, the student has a short check-in
--     window to answer "Did your problem get fixed?". Answering no reopens the
--     ticket as escalated (answer_help_request_check_in).
-- Staff "End ticket" closes a ticket with no check-in, so it can never be
-- escalated again (finish_help_request with p_end_ticket = true).
--
-- All writes go through the SECURITY DEFINER RPCs below. The RPCs set the
-- transaction-local flag pawtograder.help_request_escalation_rpc so the
-- column guard on help_requests lets their updates through; PostgREST cannot
-- call set_config, so a client cannot set that flag itself.

ALTER TYPE public.student_help_activity_type ADD VALUE IF NOT EXISTS 'request_escalated';

-- ---------------------------------------------------------------------------
-- help_requests: escalation state
-- ---------------------------------------------------------------------------

ALTER TABLE public.help_requests
  ADD COLUMN escalation_count integer NOT NULL DEFAULT 0,
  ADD COLUMN last_escalated_at timestamptz,
  ADD COLUMN check_in_expires_at timestamptz;

ALTER TABLE public.help_requests
  ADD CONSTRAINT help_requests_escalation_count_nonnegative CHECK (escalation_count >= 0);

COMMENT ON COLUMN public.help_requests.escalation_count IS
'Times this ticket has been escalated. Escalated open tickets sort ahead of normal ones.';
COMMENT ON COLUMN public.help_requests.check_in_expires_at IS
'Set when staff resolve a ticket: until this time the ticket''s students can answer "Did your problem get fixed?" and escalate. NULL when no check-in is pending.';

-- ---------------------------------------------------------------------------
-- help_request_escalations: one row per escalation
-- ---------------------------------------------------------------------------

CREATE TYPE public.help_request_escalation_source AS ENUM ('staff', 'student');

CREATE TABLE public.help_request_escalations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  class_id bigint NOT NULL REFERENCES public.classes(id) ON DELETE CASCADE,
  help_request_id bigint NOT NULL REFERENCES public.help_requests(id) ON DELETE CASCADE,
  escalated_by uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  source public.help_request_escalation_source NOT NULL,
  -- The TA who was helping (staff escalation) or who last helped (student escalation).
  previous_assignee uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  note text NOT NULL CHECK (char_length(btrim(note)) BETWEEN 1 AND 500),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_help_request_escalations_help_request_id ON public.help_request_escalations (help_request_id);
CREATE INDEX idx_help_request_escalations_class_id ON public.help_request_escalations (class_id);
CREATE INDEX idx_help_request_escalations_escalated_by ON public.help_request_escalations (escalated_by);
CREATE INDEX idx_help_request_escalations_previous_assignee ON public.help_request_escalations (previous_assignee);

ALTER TABLE public.help_request_escalations ENABLE ROW LEVEL SECURITY;

-- Notes are written for staff ("what I tried, what's still broken") and stay internal.
-- Students see that their ticket was escalated through help_requests.escalation_count.
CREATE POLICY "Staff can view escalations in their class" ON public.help_request_escalations
  FOR SELECT TO authenticated
  USING (public.authorizeforhelprequeststaff(class_id));

REVOKE INSERT, UPDATE, DELETE, TRUNCATE ON public.help_request_escalations FROM anon, authenticated;

-- ---------------------------------------------------------------------------
-- Realtime: escalation rows go to the staff channel only
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.broadcast_help_request_staff_data_change()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    help_request_id BIGINT;
    class_id BIGINT;
    student_profile_id UUID;
    row_id BIGINT;
    staff_payload JSONB;
BEGIN
    -- Get relevant IDs based on table
    IF TG_TABLE_NAME = 'help_request_moderation' THEN
        IF TG_OP = 'INSERT' THEN
            help_request_id := NEW.help_request_id;
            class_id := NEW.class_id;
            student_profile_id := NEW.student_profile_id;
            row_id := NEW.id;
        ELSIF TG_OP = 'UPDATE' THEN
            help_request_id := COALESCE(NEW.help_request_id, OLD.help_request_id);
            class_id := COALESCE(NEW.class_id, OLD.class_id);
            student_profile_id := COALESCE(NEW.student_profile_id, OLD.student_profile_id);
            row_id := COALESCE(NEW.id, OLD.id);
        ELSIF TG_OP = 'DELETE' THEN
            help_request_id := OLD.help_request_id;
            class_id := OLD.class_id;
            student_profile_id := OLD.student_profile_id;
            row_id := OLD.id;
        END IF;
    ELSIF TG_TABLE_NAME = 'student_karma_notes' THEN
        -- student_karma_notes has NO help_request_id column: karma notes are
        -- attached to a student within a class, not to one help request.
        help_request_id := NULL;
        IF TG_OP = 'INSERT' THEN
            class_id := NEW.class_id;
            student_profile_id := NEW.student_profile_id;
            row_id := NEW.id;
        ELSIF TG_OP = 'UPDATE' THEN
            class_id := COALESCE(NEW.class_id, OLD.class_id);
            student_profile_id := COALESCE(NEW.student_profile_id, OLD.student_profile_id);
            row_id := COALESCE(NEW.id, OLD.id);
        ELSIF TG_OP = 'DELETE' THEN
            class_id := OLD.class_id;
            student_profile_id := OLD.student_profile_id;
            row_id := OLD.id;
        END IF;
    ELSIF TG_TABLE_NAME = 'help_request_templates' THEN
        IF TG_OP = 'INSERT' THEN
            class_id := NEW.class_id;
            row_id := NEW.id;
        ELSIF TG_OP = 'UPDATE' THEN
            class_id := COALESCE(NEW.class_id, OLD.class_id);
            row_id := COALESCE(NEW.id, OLD.id);
        ELSIF TG_OP = 'DELETE' THEN
            class_id := OLD.class_id;
            row_id := OLD.id;
        END IF;
    ELSIF TG_TABLE_NAME = 'help_request_escalations' THEN
        IF TG_OP = 'DELETE' THEN
            help_request_id := OLD.help_request_id;
            class_id := OLD.class_id;
            row_id := OLD.id;
        ELSE
            help_request_id := NEW.help_request_id;
            class_id := NEW.class_id;
            row_id := NEW.id;
        END IF;
    END IF;

    -- Build payload
    staff_payload := jsonb_build_object(
        'type', 'staff_data_change',
        'operation', TG_OP,
        'table', TG_TABLE_NAME,
        'row_id', row_id,
        'class_id', class_id,
        'student_profile_id', student_profile_id,
        'help_request_id', help_request_id,
        'data', CASE
            WHEN TG_OP = 'DELETE' THEN to_jsonb(OLD)
            ELSE to_jsonb(NEW)
        END,
        'timestamp', NOW()
    );

    -- Always broadcast to office-hours staff channel
    IF class_id IS NOT NULL THEN
        PERFORM public.safe_broadcast(
            staff_payload,
            'broadcast',
            'help_queues:' || class_id || ':staff',
            true
        );
    END IF;

    RETURN COALESCE(NEW, OLD);
END;
$$;

COMMENT ON FUNCTION public.broadcast_help_request_staff_data_change() IS
'Broadcasts help_request_moderation, student_karma_notes, help_request_templates and help_request_escalations changes to the class staff channel. student_karma_notes is class-scoped and has no help_request_id column: reading NEW.help_request_id there aborts the write.';

CREATE TRIGGER broadcast_help_request_escalations_change
AFTER INSERT OR UPDATE OR DELETE ON public.help_request_escalations
FOR EACH ROW EXECUTE FUNCTION public.broadcast_help_request_staff_data_change();

-- ---------------------------------------------------------------------------
-- Column guard: students cannot reopen a ticket or touch escalation state
-- ---------------------------------------------------------------------------
--
-- Same function as 20261014120000_help_request_write_rls_hardening.sql, plus two
-- checks for non-staff callers:
--   * escalation_count, last_escalated_at and check_in_expires_at change only
--     through the RPCs in this migration;
--   * status may only move from open/in_progress to resolved (a student resolving
--     their own ticket). Without this, a student could PATCH a ticket staff ended
--     back to open, which would make "End ticket" meaningless.

CREATE OR REPLACE FUNCTION public.enforce_help_request_update_columns()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $$
BEGIN
  IF NEW.help_queue IS DISTINCT FROM OLD.help_queue
     AND NOT EXISTS (SELECT 1 FROM public.help_queues hq WHERE hq.id = NEW.help_queue AND hq.class_id = OLD.class_id) THEN
    RAISE EXCEPTION 'help request % cannot be moved to a queue in another class', OLD.id
      USING ERRCODE = '42501';
  END IF;

  -- Callers without a user JWT (service role, cron, admin edge functions) are trusted.
  IF auth.uid() IS NULL OR public.authorizeforhelprequeststaff(OLD.class_id) THEN
    RETURN NEW;
  END IF;

  -- The escalation RPCs validate the caller themselves and then update on their behalf.
  IF current_setting('pawtograder.help_request_escalation_rpc', true) = 'on' THEN
    RETURN NEW;
  END IF;

  IF (NEW.created_by IS DISTINCT FROM OLD.created_by AND NEW.created_by IS NOT NULL)
     OR NEW.help_queue IS DISTINCT FROM OLD.help_queue
     OR NEW.assignee IS DISTINCT FROM OLD.assignee
     OR (NEW.followup_to IS DISTINCT FROM OLD.followup_to AND NEW.followup_to IS NOT NULL)
     OR (NEW.template_id IS DISTINCT FROM OLD.template_id AND NEW.template_id IS NOT NULL) THEN
    RAISE EXCEPTION 'only course staff may change the creator, queue, assignee, follow-up or template of a help request'
      USING ERRCODE = '42501';
  END IF;

  IF NEW.escalation_count IS DISTINCT FROM OLD.escalation_count
     OR NEW.last_escalated_at IS DISTINCT FROM OLD.last_escalated_at
     OR NEW.check_in_expires_at IS DISTINCT FROM OLD.check_in_expires_at THEN
    RAISE EXCEPTION 'escalation fields of a help request change only through the escalation functions'
      USING ERRCODE = '42501';
  END IF;

  IF NEW.status IS DISTINCT FROM OLD.status
     AND NOT (NEW.status = 'resolved' AND OLD.status IN ('open', 'in_progress')) THEN
    RAISE EXCEPTION 'students may only resolve an open or in-progress help request'
      USING ERRCODE = '42501';
  END IF;

  IF NEW.resolved_by IS DISTINCT FROM OLD.resolved_by
     AND NEW.resolved_by IS NOT NULL
     AND NOT public.authorizeforprofile_in_class(NEW.resolved_by, OLD.class_id) THEN
    RAISE EXCEPTION 'resolved_by must be your own profile' USING ERRCODE = '42501';
  END IF;

  IF NEW.referenced_submission_id IS DISTINCT FROM OLD.referenced_submission_id
     AND NEW.referenced_submission_id IS NOT NULL
     AND NOT EXISTS (SELECT 1 FROM public.submissions s
                      WHERE s.id = NEW.referenced_submission_id AND s.class_id = OLD.class_id) THEN
    RAISE EXCEPTION 'referenced submission % is not in this class', NEW.referenced_submission_id
      USING ERRCODE = '22023';
  END IF;

  RETURN NEW;
END;
$$;


-- 5) Storage buckets + policies
--    Path: classes/{class_id}/exams/{exam_id}/...   (class_id at segment 2)
-- ---------------------------------------------------------------------------
insert into storage.buckets (id, name, public) values ('exam-templates','exam-templates',false)
on conflict (id) do nothing;
insert into storage.buckets (id, name, public) values ('exam-scans','exam-scans',false)
on conflict (id) do nothing;

do $$
declare
  b text;
  write_roles text;
  buckets text[] := array['exam-templates','exam-scans'];
begin
  foreach b in array buckets loop
    -- Reads are staff-wide, but WRITES diverge by bucket. exam-scans is the grader workflow --
    -- uploading and reprocessing scanned papers -- so graders need to write there. exam-templates
    -- holds the blank exam and the generated printable PDF, and every table and RPC that defines
    -- a template restricts changes to instructors; letting a grader overwrite a template object
    -- directly would desynchronize the printed paper from the instructor-controlled regions while
    -- leaving the definition untouched.
    write_roles := case when b = 'exam-templates' then '''instructor''' else '''instructor'',''grader''' end;
    -- staff read
    execute format('drop policy if exists %I on storage.objects;', b || '_staff_read');
    execute format($f$
      create policy %I on storage.objects for select to authenticated
      using (
        bucket_id = %L
        and exists (
          select 1 from public.user_privileges up
          where up.user_id = auth.uid()
            and up.class_id = (storage.foldername(name))[2]::bigint
            and up.role in ('instructor','grader')
        )
      );
    $f$, b || '_staff_read', b);
    -- staff write (insert/update/delete)
    execute format('drop policy if exists %I on storage.objects;', b || '_staff_write');
    execute format($f$
      create policy %I on storage.objects for all to authenticated
      using (
        bucket_id = %L
        and exists (
          select 1 from public.user_privileges up
          where up.user_id = auth.uid()
            and up.class_id = (storage.foldername(name))[2]::bigint
            and up.role in (%s)
        )
      )
      with check (
        bucket_id = %L
        and exists (
          select 1 from public.user_privileges up
          where up.user_id = auth.uid()
            and up.class_id = (storage.foldername(name))[2]::bigint
            and up.role in (%s)
        )
      );
    $f$, b || '_staff_write', b, write_roles, b, write_roles);
  end loop;
exception when insufficient_privilege then
  -- Some environments disallow CREATE POLICY on storage.objects (ownership varies);
  -- apply the equivalent policies via the dashboard. Local dev allows it.
  raise notice 'Skipped storage.objects policy creation (insufficient privilege).';
end $$;

-- Freeze the match once finalization has started. MatchReview writes matched_profile_id and
-- match_status directly, and it does not reload after "Create submissions" -- so the selector
-- stayed enabled with a stale null submission_id. Re-picking a student then rewrote
-- matched_profile_id while submission_id still pointed at the PREVIOUS student's submission, and
-- doing it concurrently could race exam_create_submission and leave the review row and the
-- created exam owned by different people. Enforced in the database because the client guard is
-- advisory: it cannot see a submission created a moment ago by the worker.
create or replace function public.exam_scanned_submission_freeze_match()
returns trigger
language plpgsql
as $$
begin
  if old.submission_id is not null
     and (new.matched_profile_id is distinct from old.matched_profile_id
          or new.match_status is distinct from old.match_status) then
    raise exception
      'Scanned submission % already has submission %; its match can no longer be changed (the submission would belong to a different student than the review row)',
      old.id, old.submission_id;
  end if;
  return new;
end;
$$;

drop trigger if exists trg_exam_scanned_submission_freeze_match on public.exam_scanned_submissions;
create trigger trg_exam_scanned_submission_freeze_match
  before update of matched_profile_id, match_status on public.exam_scanned_submissions
  for each row execute function public.exam_scanned_submission_freeze_match();


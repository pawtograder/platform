-- Create / upsert the exam row for an assignment (instructor only)
create or replace function public.exam_create(
  p_assignment_id bigint,
  p_source_type text default 'pdf',
  p_num_pages integer default 0,
  p_template_pdf_path text default null,
  p_template_markdown text default null
) returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_class_id bigint;
  v_exam_id bigint;
begin
  select class_id into v_class_id from public.assignments where id = p_assignment_id;
  if v_class_id is null then
    raise exception 'Assignment % not found', p_assignment_id;
  end if;
  if auth.uid() is not null and not exists (
    select 1 from public.user_privileges up
    where up.user_id = auth.uid() and up.class_id = v_class_id and up.role = 'instructor'
  ) then
    raise exception 'Access denied: instructors only';
  end if;

  insert into public.exams (class_id, assignment_id, template_source_type, num_pages,
                            template_pdf_path, template_markdown)
  values (v_class_id, p_assignment_id, p_source_type, coalesce(p_num_pages,0),
          p_template_pdf_path, p_template_markdown)
  on conflict (assignment_id) do update
    set template_source_type = excluded.template_source_type,
        num_pages = excluded.num_pages,
        template_pdf_path = coalesce(excluded.template_pdf_path, exams.template_pdf_path),
        template_markdown = coalesce(excluded.template_markdown, exams.template_markdown)
  returning id into v_exam_id;

  return v_exam_id;
end;
$$;
revoke all on function public.exam_create(bigint, text, integer, text, text) from public;
grant execute on function public.exam_create(bigint, text, integer, text, text) to authenticated, service_role;

-- Replace the full question tree + regions transactionally.
-- p_questions: [{ client_id, parent_client_id, level, ordinal, label, prompt, answer_type, choices, points }]
-- p_regions:   [{ question_client_id|null, kind, page_number, x, y, width, height }]
create or replace function public.exam_upsert_questions_and_regions(
  p_exam_id bigint,
  p_questions jsonb,
  p_regions jsonb
) returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_class_id bigint;
  q jsonb;
  r jsonb;
  v_lvl int;
  v_new_id bigint;
  v_parent_id bigint;
begin
  select class_id into v_class_id from public.exams where id = p_exam_id;
  if v_class_id is null then
    raise exception 'Exam % not found', p_exam_id;
  end if;
  if auth.uid() is not null and not exists (
    select 1 from public.user_privileges up
    where up.user_id = auth.uid() and up.class_id = v_class_id and up.role = 'instructor'
  ) then
    raise exception 'Access denied: instructors only';
  end if;

  -- wipe existing structure (regions cascade from questions, but identity regions do not)
  delete from public.exam_question_regions where exam_id = p_exam_id;
  delete from public.exam_questions where exam_id = p_exam_id;

  -- pg_temp-qualified (the function runs with search_path = '')
  create temporary table pg_temp._exam_qmap (client_id text primary key, new_id bigint) on commit drop;

  -- insert questions level-by-level so parents exist before children
  for v_lvl in 1..3 loop
    for q in select value from jsonb_array_elements(coalesce(p_questions, '[]'::jsonb))
             where (value->>'level')::int = v_lvl
             order by coalesce((value->>'ordinal')::numeric, 0)
    loop
      v_parent_id := null;
      if q->>'parent_client_id' is not null then
        select new_id into v_parent_id from pg_temp._exam_qmap where client_id = q->>'parent_client_id';
      end if;
      insert into public.exam_questions
        (class_id, exam_id, parent_id, level, ordinal, label, prompt, answer_type, choices, points)
      values
        (v_class_id, p_exam_id, v_parent_id, v_lvl,
         coalesce((q->>'ordinal')::numeric, 0), q->>'label', q->>'prompt',
         q->>'answer_type', q->'choices',
         nullif(q->>'points','')::numeric)
      returning id into v_new_id;
      insert into pg_temp._exam_qmap(client_id, new_id) values (q->>'client_id', v_new_id);
    end loop;
  end loop;

  -- regions
  for r in select value from jsonb_array_elements(coalesce(p_regions, '[]'::jsonb))
  loop
    v_new_id := null;
    if r->>'question_client_id' is not null then
      select new_id into v_new_id from pg_temp._exam_qmap where client_id = r->>'question_client_id';
    end if;
    insert into public.exam_question_regions
      (class_id, exam_id, exam_question_id, kind, page_number, x, y, width, height)
    values
      (v_class_id, p_exam_id, v_new_id, coalesce(r->>'kind','answer'),
       (r->>'page_number')::int, (r->>'x')::numeric, (r->>'y')::numeric,
       (r->>'width')::numeric, (r->>'height')::numeric);
  end loop;
end;
$$;
revoke all on function public.exam_upsert_questions_and_regions(bigint, jsonb, jsonb) from public;
grant execute on function public.exam_upsert_questions_and_regions(bigint, jsonb, jsonb) to authenticated, service_role;

-- Scaffold / link rubric_parts -> rubric_criteria -> rubric_checks from the exam's
-- 3-level question tree, writing the back-reference {exam_question_id} into each
-- component's data jsonb. Idempotent (matches on data->>'exam_question_id').
create or replace function public.exam_sync_rubric_from_questions(
  p_exam_id bigint,
  p_rubric_id bigint
) returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_class_id bigint;
  v_assignment_id bigint;
  r1 record;  -- level 1 (part)
  r2 record;  -- level 2 (criteria)
  r3 record;  -- level 3 (check)
  v_part_id bigint;
  v_crit_id bigint;
  v_check_count integer;
  v_check_points numeric;
  v_l2_count integer;
  v_l3_count integer;
  v_delivery text;
  v_in_app boolean;
begin
  select class_id, assignment_id, delivery_mode into v_class_id, v_assignment_id, v_delivery
    from public.exams where id = p_exam_id;
  -- Only an IN-APP quiz is auto-scored: quiz_autograde is reachable only from quiz_submit,
  -- which rejects anything that is not delivery_mode 'in_app'. A paper exam has no autograder
  -- at all, so its objective questions must still get a manual check to grade against.
  v_in_app := coalesce(v_delivery, 'paper') = 'in_app';
  if v_class_id is null then
    raise exception 'Exam % not found', p_exam_id;
  end if;
  if auth.uid() is not null and not exists (
    select 1 from public.user_privileges up
    where up.user_id = auth.uid() and up.class_id = v_class_id and up.role = 'instructor'
  ) then
    raise exception 'Access denied: instructors only';
  end if;

  -- The instructor check above is scoped to the EXAM's class, but every write below targets
  -- p_rubric_id, which until now was unvalidated. A caller authorized for this exam could pass
  -- any enumerable rubric id and have this security-definer function insert parts/criteria/checks
  -- into another class's rubric (stamped with this class's ids); score recomputation joins
  -- components by rubric_id, so that would alter grades in a class the caller cannot access.
  if not exists (
    select 1 from public.rubrics r
    where r.id = p_rubric_id
      and r.class_id = v_class_id
      and r.assignment_id = v_assignment_id
  ) then
    raise exception 'Rubric % does not belong to assignment %', p_rubric_id, v_assignment_id;
  end if;

  -- level 1 -> rubric_parts
  for r1 in select * from public.exam_questions where exam_id = p_exam_id and level = 1 order by ordinal loop
    select id into v_part_id from public.rubric_parts
      where rubric_id = p_rubric_id and (data->>'exam_question_id')::bigint = r1.id limit 1;
    if v_part_id is null then
      insert into public.rubric_parts (class_id, assignment_id, rubric_id, name, description, ordinal, data)
      values (v_class_id, v_assignment_id, p_rubric_id, coalesce(r1.label, 'Part'), r1.prompt, r1.ordinal,
              jsonb_build_object('exam_question_id', r1.id))
      returning id into v_part_id;
    else
      update public.rubric_parts set name = coalesce(r1.label, name), description = r1.prompt, ordinal = r1.ordinal
        where id = v_part_id;
    end if;

    -- A level-1 question with no children is a LEAF, which the flat one-question-per-prompt
    -- quiz the builder permits consists entirely of. Mapping strictly by level left such a
    -- question with a rubric part and nothing else: no criterion to carry its points and no
    -- check to award them, so its points and answer key were ungradeable. Promote the leaf to
    -- its own criterion + check under its part.
    select count(*) into v_l2_count from public.exam_questions
      where exam_id = p_exam_id and level = 2 and parent_id = r1.id;
    if v_l2_count = 0 then
      select id into v_crit_id from public.rubric_criteria
        where rubric_id = p_rubric_id and (data->>'exam_question_id')::bigint = r1.id limit 1;
      if v_crit_id is null then
        insert into public.rubric_criteria
          (class_id, assignment_id, rubric_id, rubric_part_id, name, description, total_points, is_additive, ordinal, data)
        values (v_class_id, v_assignment_id, p_rubric_id, v_part_id, coalesce(r1.label, 'Criteria'), r1.prompt,
                coalesce(r1.points, 0), true, r1.ordinal, jsonb_build_object('exam_question_id', r1.id))
        returning id into v_crit_id;
      else
        update public.rubric_criteria set rubric_part_id = v_part_id, name = coalesce(r1.label, name),
          description = r1.prompt, ordinal = r1.ordinal
          where id = v_crit_id;
      end if;
      -- INSERT-ONLY, matching the level-3 checks below: never overwrite a grader's edits.
      -- Skipped entirely for an auto-scored leaf: quiz_autograde already awards that question
      -- through grader_result_tests, and _submission_review_recompute_scores sums both channels
      -- -- so a grader ticking the manual check would count the points TWICE (or consume the
      -- assignment cap and displace points earned on hand-graded answers).
      if not (v_in_app and r1.answer_type in ('multiple_choice','true_false','numeric') and r1.correct_answer is not null)
         and not exists (
        select 1 from public.rubric_checks
        where rubric_criteria_id = v_crit_id and (data->>'exam_question_id')::bigint = r1.id
      ) then
        insert into public.rubric_checks
          (class_id, assignment_id, rubric_id, rubric_criteria_id, name, description, ordinal, points, is_annotation, is_comment_required, data)
        values (v_class_id, v_assignment_id, p_rubric_id, v_crit_id, coalesce(r1.label, 'Check'), r1.prompt, r1.ordinal,
                coalesce(r1.points, 0), false, false, jsonb_build_object('exam_question_id', r1.id));
      end if;
      select count(*), coalesce(sum(points), 0)
        into v_check_count, v_check_points
        from public.rubric_checks
        where rubric_criteria_id = v_crit_id;
      if v_check_count > 0 then
        update public.rubric_criteria set total_points = v_check_points where id = v_crit_id;
      end if;
    end if;

    -- level 2 -> rubric_criteria (children of r1)
    for r2 in select * from public.exam_questions
              where exam_id = p_exam_id and level = 2 and parent_id = r1.id order by ordinal loop
      select id into v_crit_id from public.rubric_criteria
        where rubric_id = p_rubric_id and (data->>'exam_question_id')::bigint = r2.id limit 1;
      if v_crit_id is null then
        insert into public.rubric_criteria
          (class_id, assignment_id, rubric_id, rubric_part_id, name, description, total_points, is_additive, ordinal, data)
        values (v_class_id, v_assignment_id, p_rubric_id, v_part_id, coalesce(r2.label,'Criteria'), r2.prompt,
                coalesce(r2.points, 0), true, r2.ordinal, jsonb_build_object('exam_question_id', r2.id))
        returning id into v_crit_id;
      else
        update public.rubric_criteria set rubric_part_id = v_part_id, name = coalesce(r2.label, name),
          description = r2.prompt, total_points = coalesce(r2.points, total_points), ordinal = r2.ordinal
          where id = v_crit_id;
      end if;

      -- level 3 -> rubric_checks (children of r2). Intentionally INSERT-ONLY (unlike parts
      -- and criteria above, which upsert): once a check exists we never overwrite it, so a
      -- grader's manual edits to a generated check survive re-syncing the exam structure.
      select count(*) into v_l3_count from public.exam_questions
        where exam_id = p_exam_id and level = 3 and parent_id = r2.id;
      -- Same reasoning one level down: an additive criterion with no checks has nothing to add,
      -- so a two-level tree's level-2 leaves need a check of their own.
      if v_l3_count = 0 then
        -- Same auto-scored exclusion as the level-1 leaf above.
        if not (v_in_app and r2.answer_type in ('multiple_choice','true_false','numeric') and r2.correct_answer is not null)
           and not exists (
          select 1 from public.rubric_checks
          where rubric_criteria_id = v_crit_id and (data->>'exam_question_id')::bigint = r2.id
        ) then
          insert into public.rubric_checks
            (class_id, assignment_id, rubric_id, rubric_criteria_id, name, description, ordinal, points, is_annotation, is_comment_required, data)
          values (v_class_id, v_assignment_id, p_rubric_id, v_crit_id, coalesce(r2.label, 'Check'), r2.prompt, r2.ordinal,
                  coalesce(r2.points, 0), false, false, jsonb_build_object('exam_question_id', r2.id));
        end if;
      end if;

      for r3 in select * from public.exam_questions
                where exam_id = p_exam_id and level = 3 and parent_id = r2.id order by ordinal loop
        -- Same auto-scored exclusion as the leaf cases above.
        if not (v_in_app and r3.answer_type in ('multiple_choice','true_false','numeric') and r3.correct_answer is not null)
           and not exists (
          select 1 from public.rubric_checks
          where rubric_criteria_id = v_crit_id and (data->>'exam_question_id')::bigint = r3.id
        ) then
          insert into public.rubric_checks
            (class_id, assignment_id, rubric_id, rubric_criteria_id, name, description, ordinal, points, is_annotation, is_comment_required, data)
          values (v_class_id, v_assignment_id, p_rubric_id, v_crit_id, coalesce(r3.label,'Check'), r3.prompt, r3.ordinal,
                  coalesce(r3.points, 0), false, false, jsonb_build_object('exam_question_id', r3.id));
        end if;
      end loop;

      -- Derive the criterion total from the checks that actually hang off it. A level-2 question
      -- becomes a non-leaf as soon as level-3 items exist, and the editor then hides its points
      -- control -- so r2.points stays 0 while the real points sit on the level-3 checks. Leaving
      -- the additive criterion at total_points = 0 makes _submission_review_recompute_scores cap
      -- those checks at 0, so a grader can never award them. Summing the persisted checks (rather
      -- than the exam_questions points) also keeps the total honest after a grader edits a check,
      -- which the INSERT-ONLY policy above deliberately preserves.
      select count(*), coalesce(sum(points), 0)
        into v_check_count, v_check_points
        from public.rubric_checks
        where rubric_criteria_id = v_crit_id;
      if v_check_count > 0 then
        update public.rubric_criteria set total_points = v_check_points where id = v_crit_id;
      end if;
    end loop;
  end loop;

  -- Refresh generated check points from the question while the assignment is still a DRAFT.
  -- Checks are INSERT-ONLY so a grader's edits survive a re-sync, but that also meant changing a
  -- draft question's points never reached rubric_checks.points: the criterion total summed stale
  -- checks, so manual grading used the old maximum while quiz autograding used the new value.
  -- Gating on "no submissions yet" keeps both properties -- a draft stays consistent, and once
  -- grading can have happened the grader's numbers are left alone. Only rows carrying
  -- data.exam_question_id are touched, so user-authored checks are never rewritten.
  if not exists (select 1 from public.submissions where assignment_id = v_assignment_id) then
    update public.rubric_checks c
      set points = coalesce(q.points, 0)
      from public.exam_questions q
      where c.rubric_id = p_rubric_id
        and c.data ? 'exam_question_id'
        and q.id = (c.data->>'exam_question_id')::bigint
        and q.exam_id = p_exam_id
        and c.points is distinct from coalesce(q.points, 0);
  end if;

  -- Drop generated checks whose question has BECOME auto-scored. The skip-on-insert predicates
  -- above only stop a NEW manual check being created; a free-text leaf that was synced once and
  -- later given an objective type plus an answer key kept its existing check, and the
  -- reconciliation below retains it because the question still exists -- so the recompute could
  -- sum that manual check on top of quiz_autograde's score for the same question.
  if v_in_app then
    delete from public.rubric_checks c
    using public.exam_questions q
    where c.rubric_id = p_rubric_id
      and c.data ? 'exam_question_id'
      and q.id = (c.data->>'exam_question_id')::bigint
      and q.exam_id = p_exam_id
      and q.answer_type in ('multiple_choice','true_false','numeric')
      and q.correct_answer is not null;
  end if;

  -- Reconcile: drop generated rows whose question no longer exists. exam_upsert_questions_and_
  -- regions prunes deleted questions, but this sync only ever iterated the SURVIVING ones, so a
  -- question deleted while the quiz was still a draft left its part/criterion/check behind --
  -- and _submission_review_recompute_scores kept counting that orphaned criterion for every
  -- future submission. Only rows carrying a data.exam_question_id are touched, so genuinely
  -- user-authored parts/criteria/checks are never removed. Safe to delete rather than merely
  -- hide, because the write RPC now refuses any question change once a submission exists: an
  -- orphan can only have been created while the assignment was still ungraded.
  delete from public.rubric_checks c
  where c.rubric_id = p_rubric_id
    and c.data ? 'exam_question_id'
    and not exists (
      select 1 from public.exam_questions q
      where q.exam_id = p_exam_id and q.id = (c.data->>'exam_question_id')::bigint
    );
  delete from public.rubric_criteria cr
  where cr.rubric_id = p_rubric_id
    and cr.data ? 'exam_question_id'
    and not exists (
      select 1 from public.exam_questions q
      where q.exam_id = p_exam_id and q.id = (cr.data->>'exam_question_id')::bigint
    );
  delete from public.rubric_parts pt
  where pt.rubric_id = p_rubric_id
    and pt.data ? 'exam_question_id'
    and not exists (
      select 1 from public.exam_questions q
      where q.exam_id = p_exam_id and q.id = (pt.data->>'exam_question_id')::bigint
    );
end;
$$;
revoke all on function public.exam_sync_rubric_from_questions(bigint, bigint) from public;
grant execute on function public.exam_sync_rubric_from_questions(bigint, bigint) to authenticated, service_role;

-- Create the submission for a confirmed scanned exam. Fires the existing
-- submissions_after_insert_hook (auto-creates the grading submission_review).
-- Called by the worker (service role) during finalize.
create or replace function public.exam_create_submission(p_scanned_submission_id bigint)
returns bigint
language plpgsql
security definer
-- Inserting into public.submissions fires the submission trigger chain (channels,
-- metrics, after-insert hook). Some of those triggers reference tables unqualified and
-- have no search_path of their own, so they inherit this function's. An empty search_path
-- makes them fail with "relation submissions does not exist" — keep public on the path.
set search_path = public, pg_temp
as $$
declare
  v_class_id bigint;
  v_assignment_id bigint;
  v_profile_id uuid;
  v_match_status text;
  v_existing bigint;
  v_submission_id bigint;
begin
  select ss.class_id, e.assignment_id, ss.matched_profile_id, ss.match_status, ss.submission_id
    into v_class_id, v_assignment_id, v_profile_id, v_match_status, v_existing
  from public.exam_scanned_submissions ss
  join public.exams e on e.id = ss.exam_id
  where ss.id = p_scanned_submission_id;

  if v_class_id is null then
    raise exception 'Scanned submission % not found', p_scanned_submission_id;
  end if;
  if v_existing is not null then
    return v_existing; -- idempotent
  end if;
  if v_match_status <> 'confirmed' or v_profile_id is null then
    raise exception 'Scanned submission % is not a confirmed match', p_scanned_submission_id;
  end if;

  -- Shared lock on the assignment, matching quiz_submit. FOR KEY SHARE does not conflict with
  -- itself (concurrent finalize workers proceed in parallel) but does conflict with the
  -- FOR UPDATE taken by exam_upsert_questions_and_regions, so an instructor cannot rewrite the
  -- question set while this submission's exam_v1 artifact is being written against it.
  perform 1 from public.assignments where id = v_assignment_id for key share;

  insert into public.submissions
    -- 'manual': there is no git commit behind a scanned exam, and without this the submission
    -- history renderer's `sha && repository` branch turns these synthetic values into a
    -- github.com/<repository>/commit/<sha> link that 404s.
    (assignment_id, profile_id, class_id, sha, repository, run_attempt, run_number, is_active, submitted_via)
  values
    (v_assignment_id, v_profile_id, v_class_id, 'exam',
     'exam-scan/' || p_scanned_submission_id::text, 0, 1, true, 'manual')
  returning id into v_submission_id;

  update public.exam_scanned_submissions set submission_id = v_submission_id
    where id = p_scanned_submission_id;

  return v_submission_id;
end;
$$;
revoke all on function public.exam_create_submission(bigint) from public;
grant execute on function public.exam_create_submission(bigint) to service_role;


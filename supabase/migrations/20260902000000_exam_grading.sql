create or replace function public.enqueue_exam_process_batch(p_batch_id bigint)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_class_id bigint;
  v_count integer := 0;
  v_page_count integer;
  v_total_pages integer;
  v_pages_per_exam integer;
  v_num_pages integer;
  rec record;
begin
  select class_id into v_class_id from public.exam_scan_batches where id = p_batch_id;
  if v_class_id is null then
    raise exception 'Batch % not found', p_batch_id;
  end if;
  if auth.uid() is not null and not exists (
    select 1 from public.user_privileges up
    where up.user_id = auth.uid() and up.class_id = v_class_id and up.role in ('instructor','grader')
  ) then
    raise exception 'Access denied: staff only';
  end if;

  -- Refuse to process a batch whose pages are not all persisted. uploadExamScanBatch inserts the
  -- batch row (with the full total_pages) before uploading pages, so a failure part-way leaves a
  -- processable batch holding only a prefix -- and matching would then split exams from a short
  -- page list and produce wrong student submissions. Checked here rather than only in the UI so
  -- it also holds for a direct RPC call and for the 'error' retry path.
  select count(*) into v_page_count from public.exam_scan_pages where batch_id = p_batch_id;
  select total_pages, pages_per_exam into v_total_pages, v_pages_per_exam
    from public.exam_scan_batches where id = p_batch_id;

  -- pages_per_exam must span the whole template. Staff pick it by hand, and a value below the
  -- template's page count still divides an even scan cleanly -- so pages from different students
  -- get grouped into one exam, and regions on the template pages beyond the chosen count are
  -- skipped during finalization. Checked against the exam rather than trusting any positive
  -- integer. (num_pages = 0 means the template has not been rasterized yet, so there is nothing
  -- to compare against.)
  select num_pages into v_num_pages from public.exams e
    join public.exam_scan_batches b on b.exam_id = e.id where b.id = p_batch_id;
  if coalesce(v_num_pages, 0) > 0 and v_pages_per_exam is distinct from v_num_pages then
    raise exception
      'Batch % is set to % page(s) per exam but the template has % page(s); correct pages-per-exam before processing',
      p_batch_id, v_pages_per_exam, v_num_pages;
  end if;
  if v_page_count is distinct from v_total_pages then
    raise exception 'Batch % has % of % scan pages persisted; re-upload the scan before processing',
      p_batch_id, v_page_count, v_total_pages;
  end if;

  update public.exam_scan_batches set status = 'ocr', error = null where id = p_batch_id;

  -- one OCR job per scan page
  for rec in select id from public.exam_scan_pages where batch_id = p_batch_id order by page_index loop
    perform pgmq_public.send('exam_processing', jsonb_build_object(
      'method', 'process_page', 'class_id', v_class_id, 'batch_id', p_batch_id,
      'args', jsonb_build_object('scan_page_id', rec.id)));
    v_count := v_count + 1;
  end loop;

  -- one match job for the batch (groups pages into scanned submissions, reads identity)
  perform pgmq_public.send('exam_processing', jsonb_build_object(
    'method', 'match', 'class_id', v_class_id, 'batch_id', p_batch_id,
    'args', jsonb_build_object('batch_id', p_batch_id)));

  -- best-effort immediate kick; the cron invoker drains the queue regardless
  begin
    perform public.call_edge_function_internal(
      '/functions/v1/exam-async-worker', 'POST',
      '{"Content-type":"application/json","x-supabase-webhook-source":"exam-async-worker"}'::jsonb,
      '{}'::jsonb, 3000, null, null, null, null, null);
  exception when others then null;
  end;

  return v_count;
end;
$$;
revoke all on function public.enqueue_exam_process_batch(bigint) from public;
grant execute on function public.enqueue_exam_process_batch(bigint) to authenticated, service_role;

create or replace function public.enqueue_exam_finalize(p_batch_id bigint)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_class_id bigint;
  v_count integer := 0;
  rec record;
begin
  select class_id into v_class_id from public.exam_scan_batches where id = p_batch_id;
  if v_class_id is null then
    raise exception 'Batch % not found', p_batch_id;
  end if;
  if auth.uid() is not null and not exists (
    select 1 from public.user_privileges up
    where up.user_id = auth.uid() and up.class_id = v_class_id and up.role in ('instructor','grader')
  ) then
    raise exception 'Access denied: staff only';
  end if;

  -- Refuse to start when two scanned exams are confirmed for the SAME student. The match-review
  -- selector permits it (two papers can be read as the same person), and each finalize inserts
  -- an ACTIVE individual submission -- so the first succeeds and the second violates
  -- submissions_one_active_individual_per_student, which retries and finally errors a batch
  -- that is already half finalized. Caught up front, while the batch is still wholly
  -- unfinalized and staff can fix the duplicate in review, since what SHOULD happen to a
  -- genuine duplicate scan (replace? keep both? merge?) is a product decision, not something
  -- to guess at inside a retry loop.
  if exists (
    select 1
    from public.exam_scanned_submissions ss
    where ss.batch_id = p_batch_id
      and ss.match_status = 'confirmed'
      and ss.matched_profile_id is not null
    group by ss.matched_profile_id
    having count(*) > 1
  ) then
    raise exception
      'Batch % has more than one confirmed exam for the same student; resolve the duplicate matches in review before creating submissions',
      p_batch_id;
  end if;

  -- Also reject when a confirmed student ALREADY has an active submission from an earlier
  -- batch. The in-batch duplicate check above groups only within p_batch_id, so a re-scan batch
  -- containing a student who was already finalized would partially finalize everyone else and
  -- then fail on that one insert against
  -- submissions_one_active_individual_per_student, DLQ the message and error the batch. Caught
  -- here for the same reason as the in-batch case: whether a re-scan should REPLACE the earlier
  -- submission or be refused is a product decision, and guessing it inside a retry loop is how
  -- you silently overwrite a student's graded exam.
  if exists (
    select 1
    from public.exam_scanned_submissions ss
    join public.exams e on e.id = ss.exam_id
    join public.submissions sub
      on sub.assignment_id = e.assignment_id
     and sub.profile_id = ss.matched_profile_id
     and sub.is_active
     and sub.assignment_group_id is null
    where ss.batch_id = p_batch_id
      and ss.match_status = 'confirmed'
      and ss.matched_profile_id is not null
      and ss.finalized_at is null
      and sub.id is distinct from ss.submission_id
  ) then
    raise exception
      'Batch % contains a confirmed exam for a student who already has an active submission for this assignment; resolve the duplicate (or remove the earlier submission) before creating submissions',
      p_batch_id;
  end if;

  -- Re-enqueue every confirmed submission that is not yet finalized. finalized_at is the
  -- crash-safety signal: a submission whose finalize crashed before completing (finalized_at
  -- still NULL, whether or not a partial submission/artifact exists) is picked back up here,
  -- as is one that never started.
  for rec in select ss.id from public.exam_scanned_submissions ss
             where ss.batch_id = p_batch_id and ss.match_status = 'confirmed'
               and ss.finalized_at is null loop
    perform pgmq_public.send('exam_processing', jsonb_build_object(
      'method', 'finalize', 'class_id', v_class_id, 'batch_id', p_batch_id,
      'args', jsonb_build_object('scanned_submission_id', rec.id)));
    v_count := v_count + 1;
  end loop;

  -- Only flip into 'finalizing' when there is actually work; otherwise leave the batch's
  -- status untouched (e.g. an already-'completed' batch stays completed) so a redundant
  -- finalize click can't strand it.
  if v_count > 0 then
    update public.exam_scan_batches set status = 'finalizing', error = null where id = p_batch_id;

    -- best-effort immediate kick; the cron invoker drains the queue regardless
    begin
      perform public.call_edge_function_internal(
        '/functions/v1/exam-async-worker', 'POST',
        '{"Content-type":"application/json","x-supabase-webhook-source":"exam-async-worker"}'::jsonb,
        '{}'::jsonb, 3000, null, null, null, null, null);
    exception when others then null;
    end;
  end if;

  return v_count;
end;
$$;
revoke all on function public.enqueue_exam_finalize(bigint) from public;
grant execute on function public.enqueue_exam_finalize(bigint) to authenticated, service_role;

-- Background invoker (drains the exam_processing queue via the edge worker)
create or replace function public.invoke_exam_async_worker_background_task()
returns void
language plpgsql
security definer
-- pgmq on the path for pgmq.metrics() below; public for call_edge_function_internal.
set search_path = public, pgmq
as $$
declare
  message_count integer;
  worker_count integer;
  i integer;
begin
  -- pgmq.metrics is a PASSIVE count. pgmq_public.read(..., vt => 0), which this used before,
  -- is not: read() increments read_ct on the messages it returns (up to 20 here) and makes them
  -- visible again immediately. So a backlog -- or worker invocations that fail to start -- had
  -- its read_ct bumped once a minute by the scheduler alone, and after eight polls the worker's
  -- `read_ct >= PGMQ_MAX_READ_CT` poison guard dead-lettered OCR and finalize jobs that no
  -- handler had ever attempted. Autoscaling must observe the queue, not consume it.
  select queue_length::integer into message_count from pgmq.metrics('exam_processing');
  if message_count = 0 then
    return;
  elsif message_count >= 10 then
    worker_count := 5;
  else
    worker_count := 2;
  end if;
  for i in 1..worker_count loop
    perform public.call_edge_function_internal(
      '/functions/v1/exam-async-worker', 'POST',
      '{"Content-type":"application/json","x-supabase-webhook-source":"exam-async-worker"}'::jsonb,
      '{}'::jsonb, 3000, null, null, null, null, null);
  end loop;
end;
$$;
revoke all on function public.invoke_exam_async_worker_background_task() from public;
grant execute on function public.invoke_exam_async_worker_background_task() to service_role;

select cron.unschedule('invoke-exam-async-worker-every-minute')
where exists (select 1 from cron.job where jobname = 'invoke-exam-async-worker-every-minute');
select cron.schedule(
  'invoke-exam-async-worker-every-minute',
  '* * * * *',
  $$select public.invoke_exam_async_worker_background_task();$$
);

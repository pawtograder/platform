create table if not exists public.exams (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  class_id bigint not null references public.classes(id) on delete cascade,
  assignment_id bigint not null references public.assignments(id) on delete cascade,
  template_source_type text not null default 'pdf' check (template_source_type in ('pdf','markdown')),
  template_pdf_path text,
  template_markdown text,
  num_pages integer not null default 0,
  status text not null default 'draft' check (status in ('draft','ready')),
  created_by uuid default auth.uid(),
  constraint exams_assignment_id_unique unique (assignment_id)
);

create table if not exists public.exam_template_pages (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  class_id bigint not null references public.classes(id) on delete cascade,
  exam_id bigint not null references public.exams(id) on delete cascade,
  page_number integer not null,
  image_path text not null,
  width integer not null,
  height integer not null
);

create table if not exists public.exam_questions (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  class_id bigint not null references public.classes(id) on delete cascade,
  exam_id bigint not null references public.exams(id) on delete cascade,
  parent_id bigint references public.exam_questions(id) on delete cascade,
  level smallint not null check (level between 1 and 3),
  ordinal numeric not null default 0,
  label text,
  prompt text,
  answer_type text check (answer_type in
    ('multiple_choice','free_text','numeric','true_false','short_answer')),
  choices jsonb,
  points numeric
);

-- Points must be non-negative: the rubric tables this scaffolds into carry their own
-- non-negative constraints (so a negative value fails rubric sync), and in quiz autograding a
-- negative would subtract from points the student earned legitimately elsewhere. Both question
-- editors expose a bare numeric input, so enforce it in the schema rather than trusting the UI.
-- Stated as a separate drop-then-add (ADD CONSTRAINT has no IF NOT EXISTS) so it is applied
-- even when the CREATE TABLE above no-ops against an already-existing table.
alter table public.exam_questions drop constraint if exists exam_questions_points_non_negative;
alter table public.exam_questions
  add constraint exam_questions_points_non_negative check (points is null or points >= 0);

create table if not exists public.exam_question_regions (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  class_id bigint not null references public.classes(id) on delete cascade,
  exam_id bigint not null references public.exams(id) on delete cascade,
  exam_question_id bigint references public.exam_questions(id) on delete cascade,
  kind text not null default 'answer' check (kind in ('answer','student_id','name')),
  page_number integer not null,
  x numeric not null,
  y numeric not null,
  width numeric not null,
  height numeric not null,
  -- identity regions (name / student_id) are not tied to a question
  constraint exam_region_identity_has_no_question
    check (kind = 'answer' or exam_question_id is null)
);

-- An 'answer' region with no exam_question_id is unusable: finalize filters those rows out, so
-- the student's response is absent from every artifact even though the overlay looked like a
-- valid answer box. Identity regions (student_id/name) legitimately have no question.
alter table public.exam_question_regions drop constraint if exists exam_question_regions_answer_needs_question;
alter table public.exam_question_regions
  add constraint exam_question_regions_answer_needs_question
  check (kind <> 'answer' or exam_question_id is not null);

create table if not exists public.exam_scan_batches (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  class_id bigint not null references public.classes(id) on delete cascade,
  exam_id bigint not null references public.exams(id) on delete cascade,
  uploaded_by uuid default auth.uid(),
  original_pdf_path text,
  total_pages integer not null default 0,
  pages_per_exam integer not null default 1,
  status text not null default 'uploaded'
    check (status in ('uploaded','ocr','matching','review','finalizing','completed','error')),
  error text
);

create table if not exists public.exam_scanned_submissions (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  class_id bigint not null references public.classes(id) on delete cascade,
  exam_id bigint not null references public.exams(id) on delete cascade,
  batch_id bigint not null references public.exam_scan_batches(id) on delete cascade,
  exam_index integer not null,
  detected_name text,
  detected_sis_id text,
  matched_profile_id uuid references public.profiles(id) on delete set null,
  match_confidence numeric,
  match_status text not null default 'unmatched'
    check (match_status in ('unmatched','suggested','confirmed','skipped')),
  extracted jsonb,
  submission_id bigint references public.submissions(id) on delete set null,
  -- Single completion marker for this scanned submission's finalize. Set (transactionally
  -- at the end of finalize) only once the submission, its page files, and the exam artifact
  -- are all written. NULL = not finalized (never started OR crashed mid-finalize), which is
  -- exactly the set enqueue_exam_finalize re-enqueues and maybeCompleteBatch waits on.
  finalized_at timestamptz
);

create table if not exists public.exam_scan_pages (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  class_id bigint not null references public.classes(id) on delete cascade,
  exam_id bigint not null references public.exams(id) on delete cascade,
  batch_id bigint not null references public.exam_scan_batches(id) on delete cascade,
  page_index integer not null,
  image_path text not null,
  width integer not null,
  height integer not null,
  ocr_text text,
  ocr_data jsonb,
  scanned_submission_id bigint references public.exam_scanned_submissions(id) on delete set null
);

-- COMPOSITE class-coupled foreign keys. The single-column FKs above do not tie a parent id to
-- a class, which is what allowed an instructor in class A to attach an exam to class B's
-- assignment (RLS was satisfied by the row's own class_id = A). The write policies validate the
-- same rule, but a foreign key also constrains service-role writers and cannot be bypassed by a
-- future code path. assignments already carries UNIQUE (id, class_id), so no shared table needs
-- changing; the new tables get the matching unique keys to be referenced.
alter table public.exams drop constraint if exists exams_id_class_id_key;
alter table public.exams add constraint exams_id_class_id_key unique (id, class_id);
alter table public.exam_scan_batches drop constraint if exists exam_scan_batches_id_class_id_key;
alter table public.exam_scan_batches add constraint exam_scan_batches_id_class_id_key unique (id, class_id);

alter table public.exams drop constraint if exists exams_assignment_class_fkey;
alter table public.exams
  add constraint exams_assignment_class_fkey
  foreign key (assignment_id, class_id) references public.assignments (id, class_id) on delete cascade;

do $$
declare
  t text;
  child_tables text[] := array['exam_template_pages','exam_questions','exam_question_regions',
                               'exam_scan_batches','exam_scanned_submissions'];
begin
  foreach t in array child_tables loop
    execute format('alter table public.%I drop constraint if exists %I;', t, t || '_exam_class_fkey');
    execute format(
      'alter table public.%I add constraint %I foreign key (exam_id, class_id) '
      || 'references public.exams (id, class_id) on delete cascade;', t, t || '_exam_class_fkey');
  end loop;
end $$;

alter table public.exam_scan_pages drop constraint if exists exam_scan_pages_batch_class_fkey;
alter table public.exam_scan_pages
  add constraint exam_scan_pages_batch_class_fkey
  foreign key (batch_id, class_id) references public.exam_scan_batches (id, class_id) on delete cascade;


